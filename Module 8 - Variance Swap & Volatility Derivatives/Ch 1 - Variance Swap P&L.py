import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import norm

def simulate_heston(S0, v0, kappa, theta, xi, rho, r, T, n_days, n_paths):
    dt = T / n_days
    S = np.zeros((n_paths, n_days + 1))
    v = np.zeros((n_paths, n_days + 1))
    S[:, 0] = S0
    v[:, 0] = v0

    for t in range(n_days):
        # Correlated Brownian motions
        Z1 = np.random.standard_normal(n_paths)
        Z2 = rho * Z1 + np.sqrt(1 - rho**2) * np.random.standard_normal(n_paths)

        # Variance process (full truncation scheme)
        v_pos = np.maximum(v[:, t], 0)
        v[:, t+1] = v[:, t] + kappa * (theta - v_pos) * dt + xi * np.sqrt(v_pos * dt) * Z2
        v[:, t+1] = np.maximum(v[:, t+1], 0)  # Reflect at 0

        # Stock process
        S[:, t+1] = S[:, t] * np.exp((r - 0.5 * v_pos) * dt + np.sqrt(v_pos * dt) * Z1)

    return S, v

def compute_realized_variance(S, annualization=252):
    log_returns = np.diff(np.log(S), axis=1)
    n = log_returns.shape[1]
    rv = annualization / n * np.sum(log_returns**2, axis=1)
    return rv

def variance_swap_pnl(S0=100, v0=0.04, kappa=2.0, theta=0.04, xi=0.3, rho=-0.7, r=0.02, T=0.25,
                      K_var=0.0484, N_var=454545, n_paths=50000):
    np.random.seed(12)
    n_days = int(252 * T)

    S, v = simulate_heston(S0, v0, kappa, theta, xi, rho, r, T, n_days, n_paths)
    rv = compute_realized_variance(S)
    pnl = N_var * (rv - K_var)  # Long variance payoff

    # Statistics
    print('=' * 55)
    print(" VARIANCE SWAP P&L ANALYSIS (Heston Model)")
    print('=' * 55)
    print(f" Strike K_var : {K_var:.4f} ({np.sqrt(K_var)*100:.2f}%^2)")
    print(f" E[RV ]: {rv.mean():.4f} ({np.sqrt(rv.mean())*100:.2f}%^2)")
    print(f" Std[RV ]: {rv.std():.4f}")
    print(f" E[P&L]: ${pnl.mean():,.0f}")
    print(f" Std[P&L]: ${pnl.std():,.0f}")
    print(f" 95th pctile loss : ${np.percentile(pnl, 5):,.0f}")
    print(f" 99th pctile loss : ${np.percentile(pnl, 1):,.0f}")
    print(f" Max loss : ${pnl.min():,.0f}")
    print(f" Prob (RV > K): {(rv > K_var).mean()*100:.1f}%")
    print('=' * 55)

    # Plot
    fig, axes = plt.subplots(1, 2, figsize=(14, 5))

    axes[0].hist(np.sqrt(rv) * 100, bins=100, color='steelblue', alpha=0.7, edgecolor='navy', linewidth=0.5)
    axes[0].axvline(np.sqrt(K_var) * 100, color='red', lw=2, label=f'Strike: {np.sqrt(K_var)*100:.1f}%')
    axes[0].axvline(np.sqrt(rv.mean()) * 100, color='green', lw=2, label=f'E[RVol]: {np.sqrt(rv.mean())*100:.2f}%')
    axes[0].set_xlabel('Realized Volatility (%)')
    axes[0].set_ylabel('Frequency')
    axes[0].set_title('Distribution of Realized Vol (Heston)')
    axes[0].legend()

    axes[1].hist(pnl / 1e3, bins=100, color='darkorange', alpha=0.7, edgecolor='saddlebrown', linewidth=0.5)
    axes[1].axvline(0, color='black', lw=2, linestyle='--')
    axes[1].axvline(pnl.mean() / 1e3, color='green', lw=2, label=f'E[P&L]: ${pnl.mean()/1e3:.1f}K')
    axes[1].set_xlabel('P&L ($000s)')
    axes[1].set_ylabel('Frequency')
    axes[1].set_title('Variance Swap P&L Distribution')
    axes[1].legend()

    plt.tight_layout()
    plt.savefig('variance_swap_pnl.png', dpi=150, bbox_inches='tight')
    plt.show()
    return rv, pnl

# Run simulation
rv, pnl = variance_swap_pnl()


import numpy as np
import pandas as pd

def dispersion_trade_analysis(w, sigma_constituents, sigma_index, K_var_index, K_var_constituents, N_index_vega=1_000_000):
    n = len(w)

    # Index variance notional
    N_index_var = N_index_vega / (2 * sigma_index)

    # Vega-neutral sizing for constituents
    N_const_vega = [w[i] * sigma_constituents[i] / sigma_index * N_index_vega for i in range(n)]
    N_const_var = [N_const_vega[i] / (2 * sigma_constituents[i]) for i in range(n)]

    # Compute implied correlation
    weighted_vol = np.dot(w, sigma_constituents)
    weighted_var = np.dot(w**2, sigma_constituents**2)
    rho_imp = (sigma_index**2 - weighted_var) / (weighted_vol**2 - weighted_var)

    print('=' * 60)
    print(" DISPERSION TRADE ANALYSIS ")
    print('=' * 60)
    print(f" Index vol (implied): {sigma_index * 100:.1f}%")
    print(f" Weighted constituent vol: {weighted_vol * 100:.1f}%")
    print(f" Implied correlation: {rho_imp * 100:.1f}%")
    print("\n Position sizing:")
    print(f" Short index variance notional: ${N_index_var:,.0f}")

    for i in range(min(n, 5)):
        print(f" Long stock {i+1} var notional: ${N_const_var[i]:,.0f} (weight={w[i]:.2f}, vol={sigma_constituents[i]*100:.1f}%)")
    print(" ...")

    # P&L sensitivity to realized correlation
    rho_range = np.linspace(0, 1, 50)
    pnl_by_rho = []
    for rho_r in rho_range:
        # Under homogeneous realized correlation
        rv_index = rho_r * weighted_vol**2 + (1 - rho_r) * weighted_var
        rv_const = sigma_constituents**2  # assume perfect forecast of single-name vol

        pnl_index = -N_index_var * (rv_index - K_var_index)
        pnl_const = sum(N_const_var[i] * (rv_const[i] - K_var_constituents[i]) for i in range(n))
        pnl_by_rho.append(pnl_index + pnl_const)

    pnl_by_rho = np.array(pnl_by_rho)

    # Break-even correlation
    breakeven_idx = np.argmin(np.abs(pnl_by_rho))
    rho_be = rho_range[breakeven_idx]
    print(f"\n Break-even realized correlation: {rho_be * 100:.1f}%")
    print(f" P&L at rho = 0.4 (typical): ${np.interp(0.4, rho_range, pnl_by_rho):,.0f}")
    print(f" P&L at rho = 0.8 (crisis): ${np.interp(0.8, rho_range, pnl_by_rho):,.0f}")
    print('=' * 60)

    return rho_range, pnl_by_rho

# Example: 5-stock mini-index
np.random.seed(0)
w = np.array([0.25, 0.20, 0.20, 0.20, 0.15])
sigma_c = np.array([0.25, 0.30, 0.28, 0.35, 0.22])
sigma_I = 0.22  # index vol (lower due to diversification)

rho_range, pnl = dispersion_trade_analysis(
    w=w,
    sigma_constituents=sigma_c,
    sigma_index=sigma_I,
    K_var_index=sigma_I**2,
    K_var_constituents=sigma_c**2
)

import matplotlib.pyplot as plt

# Find break-even correlation automatically
rho_be = rho_range[np.argmin(np.abs(pnl))]

plt.figure(figsize=(10, 6))
plt.plot(rho_range * 100, pnl, color='purple', lw=2.5, label='Dispersion Trade P&L')

# Highlight break-even and regimes
plt.axhline(0, color='black', linestyle='-', linewidth=0.8)
plt.axvline(rho_be * 100, color='red', linestyle='--', label=f'Break-even Correlation ({rho_be * 100:.1f}%)')

# Highlight specific points
pnl_typical = np.interp(0.4, rho_range, pnl)
pnl_crisis = np.interp(0.8, rho_range, pnl)
plt.scatter([40, 80], [pnl_typical, pnl_crisis], color='darkred', zorder=5)

plt.annotate(f'Typical Market (rho=40%)\n P&L: ${pnl_typical:,.0f}',
             xy=(40, pnl_typical), xytext=(15, pnl_typical + 15000),
             arrowprops=dict(facecolor='black', arrowstyle='->', alpha=0.7))

plt.annotate(f'Market Crisis (rho=80%)\n P&L: ${pnl_crisis:,.0f}',
             xy=(80, pnl_crisis), xytext=(55, pnl_crisis - 25000),
             arrowprops=dict(facecolor='black', arrowstyle='->', alpha=0.7))

plt.title('Dispersion Trade P&L Sensitivity vs. Realized Correlation', fontsize=14)
plt.xlabel('Realized Correlation (%)', fontsize=12)
plt.ylabel('P&L ($)', fontsize=12)
plt.xlim(0, 100)
plt.grid(True, linestyle=':', alpha=0.6)
plt.legend(fontsize=11)
plt.tight_layout()
plt.savefig('dispersion_pnl_sensitivity.png', dpi=150, bbox_inches='tight')
plt.show()


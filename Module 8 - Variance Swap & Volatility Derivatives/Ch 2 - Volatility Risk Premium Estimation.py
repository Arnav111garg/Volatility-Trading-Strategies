import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import pearsonr

def estimate_vrp_from_data(rv_series, iv_series, window_fwd=21):
    vrp = iv_series**2 - rv_series.shift(-window_fwd)
    return vrp

def simulate_short_variance_strategy(
    n_months=120, kvar_mean=0.0484, kvar_std=0.008,
    rv_mean=0.04, rv_std=0.012, vrp_mean=0.008,
    tail_prob=0.02, tail_rv=0.25, N_vega=100000):
    np.random.seed(12)
    pnl_series = []
    kvar_series = []
    rv_series = []

    for m in range(n_months):
        # Simulate variance strike (implied)
        K_var = np.random.normal(kvar_mean, kvar_std)
        K_var = max(K_var, 0.01)

        # Simulate realized variance (with occasional crash)
        is_crash = np.random.random() < tail_prob
        if is_crash:
            RV = tail_rv**2 + np.random.exponential(0.01)
        else:
            RV = np.random.normal(rv_mean, rv_std)
            RV = max(RV, 0.001)

        N_var = N_vega / (2 * np.sqrt(K_var))
        pnl = -N_var * (RV - K_var)  # Short variance

        pnl_series.append(pnl)
        kvar_series.append(K_var)
        rv_series.append(RV)

    pnl_array = np.array(pnl_series)
    cumulative = np.cumsum(pnl_array)
    months = np.arange(n_months)

    # Compute statistics
    vrp_series = np.array(kvar_series) - np.array(rv_series)
    sharpe = pnl_array.mean() / pnl_array.std() * np.sqrt(12)

    print('=' * 55)
    print(f" SHORT VARIANCE STRATEGY BACKTEST ({n_months} months)")
    print('=' * 55)
    print(f" Monthly mean P&L: ${pnl_array.mean():>10,.0f}")
    print(f" Monthly std P&L:  ${pnl_array.std():>10,.0f}")
    print(f" Annualized Sharpe: {sharpe:>10.2f}")
    print(f" Win rate:         {(pnl_array > 0).mean() * 100:>9.1f}%")
    print(f" Worst month:      ${pnl_array.min():>10,.0f}")
    print(f" Max drawdown:     ${-np.max(np.maximum.accumulate(cumulative) - cumulative):>10,.0f}")

    mean_kvar_vol = np.sqrt(np.array(kvar_series)).mean() * 100
    mean_rv_vol = np.sqrt(np.array(rv_series)).mean() * 100
    diff_vol_vp = (np.sqrt(np.array(kvar_series)) - np.sqrt(np.array(rv_series))).mean() * 100

    print(f" Mean VRP (vol):   {mean_kvar_vol:.2f}% - {mean_rv_vol:.2f}% = {diff_vol_vp:.2f} vp")
    print('=' * 55)

    return pd.DataFrame({
        'month': months,
        'pnl': pnl_array,
        'cumulative_pnl': cumulative,
        'kvar': kvar_series,
        'rv': rv_series,
        'vrp': vrp_series
    })

results = simulate_short_variance_strategy()

import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# Convert variance back to volatility percentage
vol_strike_pct = np.sqrt(results['kvar']) * 100
realized_vol_pct = np.sqrt(results['rv']) * 100

plt.figure(figsize=(12, 6))

# Plot overlapping histograms with KDE
sns.histplot(vol_strike_pct, kde=True, color='blue', label='Variance Strike ($K_{var}$ Vol)', stat='density', alpha=0.4, bins=30)
sns.histplot(realized_vol_pct, kde=True, color='orange', label='Realized Volatility (RV Vol)', stat='density', alpha=0.4, bins=30)

# Add labels and details
plt.title('Distribution Comparison: Implied/Strike Volatility vs Realized Volatility', fontsize=14)
plt.xlabel('Volatility (%)', fontsize=12)
plt.ylabel('Density', fontsize=12)
plt.axvline(vol_strike_pct.mean(), color='blue', linestyle='--', linewidth=1.5, label=f'Mean Strike: {vol_strike_pct.mean():.2f}%')
plt.axvline(realized_vol_pct.mean(), color='orange', linestyle='--', linewidth=1.5, label=f'Mean Realized: {realized_vol_pct.mean():.2f}%')

plt.legend(fontsize=11)
plt.grid(True, linestyle=':', alpha=0.6)
plt.tight_layout()
plt.show()


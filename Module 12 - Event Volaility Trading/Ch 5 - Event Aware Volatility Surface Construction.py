import numpy as np
from scipy.interpolate import interp1d
from scipy.optimize import brentq
from scipy.stats import norm

class EventAwareVolSurface:
    def __init__(self, sigma_c: float, events: list):
        self.sigma_c = sigma_c
        self.events = sorted(events, key=lambda x: x[0])  # sort by time

    def total_variance(self, T: float) -> float:
        var = self.sigma_c**2 * T
        for (tau, sigma_J) in self.events:
            if T >= tau:
                var += sigma_J**2
        return var

    def implied_vol(self, T: float) -> float:
        """Implied vol at expiry T."""
        if T <= 0: return self.sigma_c
        return np.sqrt(self.total_variance(T) / T)

    def forward_variance(self, T1: float, T2: float) -> float:
        """
        Forward variance between T1 and T2. Must be non-negative.
        """
        var1 = self.total_variance(T1)
        var2 = self.total_variance(T2)
        fwd_var = (var2 - var1) / (T2 - T1)
        assert fwd_var >= 0, f"Calendar arbitrage! fwd_var ={fwd_var:.6f}"
        return fwd_var

    def vol_surface_2d(self, T_grid: np.ndarray, K_grid: np.ndarray, skew_params: dict = None) -> np.ndarray:
        if skew_params is None:
            skew_params = {'slope': -1.0, 'curve': 0.5}

        surface = np.zeros((len(K_grid), len(T_grid)))

        for j, T in enumerate(T_grid):
            iv_atm = self.implied_vol(T)
            for i, K in enumerate(K_grid):
                m = np.log(K)  # log-moneyness (F=1 normalized)

                # SVI-style smile adjustment (simplified)
                smile_adj = (skew_params['slope'] * m + skew_params['curve'] * m**2) / np.sqrt(T)

                # Event-induced smile (symmetric jump contribution)
                ev_var = sum(sigma_J**2 for tau, sigma_J in self.events if T >= tau)
                if ev_var > 0 and T > 0:
                    ev_smile = ev_var * m**2 / (2 * self.sigma_c * T * (ev_var + m**2/4))
                else:
                    ev_smile = 0

                total_iv = iv_atm + smile_adj + ev_smile
                surface[i, j] = max(total_iv, 0.01)  # Floor at 1%

        return surface

    def check_no_arbitrage(self, T_grid: np.ndarray) -> dict:
        results = {'calendar_arb': [], 'forward_vars': []}

        for i in range(len(T_grid) - 1):
            T1, T2 = T_grid[i], T_grid[i+1]
            fwd_var = (self.total_variance(T2) - self.total_variance(T1)) / (T2 - T1)
            results['forward_vars'].append(fwd_var)

            if fwd_var < -1e-8:
                results['calendar_arb'].append((T1, T2, fwd_var))

        results['has_calendar_arb'] = len(results['calendar_arb']) > 0
        return results

events = [
    (7/252, 0.045),   # Earnings in 7 days, 4.5% jump vol
    (35/252, 0.035),  # Next earnings in ~35 days
]

surface = EventAwareVolSurface(sigma_c=0.22, events=events)

T_grid = np.array([5/252, 7/252, 10/252, 14/252, 21/252, 28/252, 35/252, 63/252])
labels = ['5D', '7D', '10D', '2W', '3W', '4W', '5W', '3M']

print("=== Event-Aware Vol Term Structure ===")
print(f"{'Expiry': >8} | {'IV (%)': >8} | {'TotalVar': >10} | {'FwdVar': >10}")
print("-" * 45)
prev_T = 0
for T, lbl in zip(T_grid, labels):
    iv = surface.implied_vol(T)
    tv = surface.total_variance(T)
    if prev_T > 0:
        fv = surface.forward_variance(prev_T, T)
    else:
        fv = iv**2
    print(f"{lbl: >8} | {iv * 100: >8.2f} | {tv: >10.6f} | {fv: >10.6f}")
    prev_T = T

arb_check = surface.check_no_arbitrage(T_grid)
print(f"\nCalendar Arbitrage Detected: {arb_check['has_calendar_arb']}")


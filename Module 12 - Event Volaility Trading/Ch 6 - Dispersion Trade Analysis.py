import numpy as np
import pandas as pd

class DispersionTradeAnalyzer:
    def __init__(self, weights: np.ndarray, stock_ivs: np.ndarray, index_iv: float, corr_matrix: np.ndarray):
        self.w = np.array(weights)
        self.sigmas = np.array(stock_ivs)
        self.sigma_idx = index_iv
        self.rho = np.array(corr_matrix)

    def fair_index_vol(self) -> float:
        sigma_cov = np.outer(self.sigmas, self.sigmas) * self.rho
        var_idx = self.w @ sigma_cov @ self.w
        return np.sqrt(var_idx)

    def implied_correlation(self) -> float:
        n = len(self.w)
        # Diagonal variance
        diag_var = np.sum(self.w**2 * self.sigmas**2)

        # Off-diagonal numerator (no correlation)
        off_diag = 0.0
        for i in range(n):
            for j in range(i + 1, n):
                off_diag += 2 * self.w[i] * self.w[j] * self.sigmas[i] * self.sigmas[j]

        if off_diag == 0:
            return 0.0

        rho_implied = (self.sigma_idx**2 - diag_var) / off_diag
        return np.clip(rho_implied, -1.0, 1.0)

    def dispersion_pnl(
        self,
        realized_returns: np.ndarray,
        var_notional_idx: float = 1e6,
        var_notional_stocks: np.ndarray = None
    ) -> dict:
        if var_notional_stocks is None:
            # Vega-neutral sizing
            var_notional_stocks = var_notional_idx * self.w

        # Realized variances
        rv_stocks = np.var(realized_returns, axis=0) * 252  # Annualized
        rv_index = np.var(realized_returns @ self.w, axis=0) * 252

        # Variance swap P&L
        pnl_idx = -var_notional_idx * (rv_index - self.sigma_idx**2)
        pnl_stocks = np.sum(var_notional_stocks * (rv_stocks - self.sigmas**2))

        total_pnl = pnl_idx + pnl_stocks

        # Realized correlation
        corr_realized = np.corrcoef(realized_returns.T)
        avg_corr_realized = (np.sum(corr_realized) - len(self.w)) / (len(self.w)**2 - len(self.w))

        return {
            'total_pnl': total_pnl,
            'pnl_short_idx': pnl_idx,
            'pnl_long_stocks': pnl_stocks,
            'rv_index': rv_index,
            'iv_index': self.sigma_idx,
            'avg_rv_stocks': rv_stocks.mean(),
            'avg_iv_stocks': self.sigmas.mean(),
            'implied_corr': self.implied_correlation(),
            'realized_corr': avg_corr_realized,
            'corr_premium': self.implied_correlation() - avg_corr_realized
        }

np.random.seed(12)
n_stocks = 10
w = np.full(n_stocks, 1/n_stocks)  # Equal weights

sigma_stocks = np.random.uniform(0.30, 0.60, n_stocks)  # Elevated due to earnings
rho_true = 0.20 * np.ones((n_stocks, n_stocks)) + 0.80 * np.eye(n_stocks)  # Realized

sigma_idx_fair = np.sqrt(w @ (np.outer(sigma_stocks, sigma_stocks) * rho_true) @ w)
sigma_idx_market = sigma_idx_fair * 1.15  # Market overprices index vol by 15%

disp = DispersionTradeAnalyzer(w, sigma_stocks, sigma_idx_market, rho_true)

print(f"Fair index vol: {disp.fair_index_vol() * 100:.2f}%")
print(f"Market index vol: {sigma_idx_market * 100:.2f}%")
print(f"Implied correlation: {disp.implied_correlation():.4f}")
print(f"True correlation: {0.20:.4f}")
print(f"Correlation premium: {disp.implied_correlation() - 0.20:.4f}")

# Simulate returns for P&L
L = np.linalg.cholesky(rho_true)
raw = np.random.standard_normal((60, n_stocks))  # 60-day window
returns = raw @ L.T * sigma_stocks / np.sqrt(252)

result = disp.dispersion_pnl(returns)
print(f"\nDispersion Trade P&L: ${result['total_pnl']:.2f}")
print(f"Short index P&L: ${result['pnl_short_idx']:.2f}")
print(f"Long stocks P&L: ${result['pnl_long_stocks']:.2f}")


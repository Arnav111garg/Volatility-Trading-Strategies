import numpy as np
import pandas as pd
from scipy import stats
import matplotlib.pyplot as plt

def compute_earnings_moves(prices: pd.DataFrame, earnings_dates: pd.DataFrame) -> pd.DataFrame:
    moves = []
    for _, row in earnings_dates.iterrows():
        ticker = row['ticker']
        edate = pd.Timestamp(row['earnings_date'])

        stock_px = prices[prices['ticker'] == ticker].set_index('date')['close']

        try:
            pre = stock_px.loc[:edate].iloc[-2]
            post = stock_px.loc[edate:].iloc[0]
            log_ret = np.log(post / pre)
            moves.append({'ticker': ticker, 'date': edate, 'log_ret': log_ret})
        except (IndexError, KeyError):
            continue

    return pd.DataFrame(moves)

def calibrate_jump_params(moves: pd.DataFrame) -> dict:
    lr = moves['log_ret'].dropna()

    mu_j, sigma_j = stats.norm.fit(lr)

    mu_j_mom = lr.mean()
    sigma_j_mom = lr.std()

    pct_range = np.percentile(np.abs(lr), [25, 50, 75, 90, 95])

    ks_stat, ks_pval = stats.kstest(lr, 'norm', args=(mu_j, sigma_j))

    kurt = stats.kurtosis(lr, fisher=True)
    skew = stats.skew(lr)

    return {
        'mu_J': mu_j,
        'sigma_J': sigma_j,
        'excess_kurt': kurt,
        'skew': skew,
        'pct_range': pct_range,
        'ks_stat': ks_stat,
        'ks_pval': ks_pval,
        'n_events': len(lr)
    }

def expected_move_from_iv(spot: float, iv_atm: float, t_years: float, method: str = 'straddle') -> float:
    if method == 'straddle':
        em = spot * iv_atm * np.sqrt(t_years) * np.sqrt(2 / np.pi)
    elif method == 'simple':
        em = spot * iv_atm * np.sqrt(t_years)
    return em

def earnings_vol_from_term_structure(iv_pre: float, t_pre: float, iv_post: float, t_post: float, t_event: float) -> float:
    var_post = iv_post ** 2 * t_post
    sigma_c_sq = var_post / t_post

    var_pre = iv_pre ** 2 * t_pre

    var_event = var_pre - sigma_c_sq * t_pre

    sigma_J = np.sqrt(max(var_event, 0.0))
    return sigma_J


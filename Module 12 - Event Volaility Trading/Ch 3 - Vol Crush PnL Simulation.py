import numpy as np
from scipy.stats import norm

def bs_greeks(S, K, T, sigma, r=0.0, q=0.0):
    if T <= 0:
        delta = 1.0 if S > K else 0.0
        return {
            'delta_c': delta,
            'delta_p': delta - 1.0,
            'gamma': 0.0,
            'vega': 0.0,
            'theta_c': 0.0,
            'theta_p': 0.0,
            'call': max(S - K, 0.0),
            'put': max(K - S, 0.0)
        }

    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)

    call = S * np.exp(-q * T) * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    put = call - S * np.exp(-q * T) + K * np.exp(-r * T)  # put-call parity

    delta_c = np.exp(-q * T) * norm.cdf(d1)
    delta_p = np.exp(-q * T) * (norm.cdf(d1) - 1.0)
    gamma = np.exp(-q * T) * norm.pdf(d1) / (S * sigma * np.sqrt(T))
    vega = S * np.exp(-q * T) * norm.pdf(d1) * np.sqrt(T) / 100.0  # per 1 vol pt

    # Theta per calendar day
    theta_c = (-(S * np.exp(-q * T) * norm.pdf(d1) * sigma) / (2.0 * np.sqrt(T)) -
               r * K * np.exp(-r * T) * norm.cdf(d2) +
               q * S * np.exp(-q * T) * norm.cdf(d1)) / 252.0
    theta_p = theta_c + r * K * np.exp(-r * T) / 252.0 - q * S * np.exp(-q * T) / 252.0

    return {
        'call': call, 'put': put,
        'delta_c': delta_c, 'delta_p': delta_p,
        'gamma': gamma, 'vega': vega,
        'theta_c': theta_c, 'theta_p': theta_p
    }

def simulate_short_straddle_earnings(
    S0=100, K=100, T_expiry=14/252,
    sigma_pre=0.45, sigma_post=0.25,
    n_simulations=10000, sigma_J=0.05,
    t_hold_pre=0.5/252
):
    np.random.seed(12)

    # Pre-earnings: enter short straddle
    greeks_pre = bs_greeks(S0, K, T_expiry, sigma_pre)
    straddle_premium = greeks_pre['call'] + greeks_pre['put']

    # Simulate earnings moves (jump only)
    eps = np.random.standard_normal(n_simulations)
    log_returns = sigma_J * eps  # Event-day log return
    S_post = S0 * np.exp(log_returns)

    # T remaining after event
    T_post = T_expiry - t_hold_pre

    # Post-earnings straddle value (crush happened)
    pnl = np.zeros(n_simulations)
    vol_crush_pnl = np.zeros(n_simulations)
    gamma_pnl = np.zeros(n_simulations)

    for i, S1 in enumerate(S_post):
        g_post = bs_greeks(S1, K, T_post, sigma_post)
        straddle_post = g_post['call'] + g_post['put']

        # Total P&L (short straddle)
        pnl[i] = straddle_premium - straddle_post

        # Attribution
        # Vega P&L: -vega * delta_sigma
        delta_sigma = (sigma_post - sigma_pre) * 100.0  # in vol pts
        vol_crush_pnl[i] = -greeks_pre['vega'] * delta_sigma * 2.0  # straddle has 2x vega

        # Gamma P&L: -0.5 * gamma * dS^2
        dS = S1 - S0
        gamma_pnl[i] = -0.5 * greeks_pre['gamma'] * 2.0 * dS**2

    # Theta P&L (negligible for short hold)
    theta_pnl = (greeks_pre['theta_c'] + greeks_pre['theta_p']) * t_hold_pre * 252.0 * (-1.0)

    results = {
        'pnl': pnl,
        'vol_crush_pnl': vol_crush_pnl,
        'gamma_pnl': gamma_pnl,
        'theta_pnl': theta_pnl,
        'straddle_premium': straddle_premium,
        'mean_pnl': pnl.mean(),
        'std_pnl': pnl.std(),
        'sharpe': pnl.mean() / pnl.std() * np.sqrt(252.0 / (4.0 * 14.0)),  # Annualized
        'win_rate': (pnl > 0).mean(),
        'max_loss': pnl.min(),
        'expected_move': straddle_premium / S0,
        'breakeven': straddle_premium / S0
    }

    print("=== Short Straddle Earnings Simulation ===")
    print(f"Straddle Premium: ${straddle_premium:.2f} ({straddle_premium / S0 * 100:.2f}%)")
    print(f"Vol pre/post: {sigma_pre * 100:.1f}% / {sigma_post * 100:.1f}%")
    print(f"Mean PnL: ${pnl.mean():.2f}")
    print(f"Std PnL: ${pnl.std():.2f}")
    print(f"Win Rate: {(pnl > 0).mean() * 100:.1f}%")
    print(f"Max Loss: ${pnl.min():.2f}")
    print(f"Avg Gamma PnL: ${gamma_pnl.mean():.2f}")
    print(f"Avg Vol Crush PnL: ${vol_crush_pnl.mean():.2f}")

    return results

results = simulate_short_straddle_earnings(
    S0=100, K=100, T_expiry=10/252,
    sigma_pre=0.45, sigma_post=0.22, sigma_J=0.04
)


import numpy as np
import pandas as pd
from scipy.optimize import minimize
from scipy.stats import norm
from typing import List, Tuple, Dict

class InstitutionalEventVolStrategy:
    def __init__(
        self,
        gross_vega_limit: float = 5e6,      # $5M gross vega
        max_single_vega: float = 5e5,       # $500K per position
        kelly_fraction: float = 0.25,       # Quarter Kelly
        min_ivp: float = 50.0,              # Min IV percentile to trade
        min_em_ratio: float = 1.15          # Min implied/hist EM ratio
    ):
        self.gross_vega_limit = gross_vega_limit
        self.max_single_vega = max_single_vega
        self.kelly_fraction = kelly_fraction
        self.min_ivp = min_ivp
        self.min_em_ratio = min_em_ratio

    def generate_signal(
        self, ticker: str, iv_current: float, iv_percentile: float,
        hist_avg_em: float, implied_em: float, analyst_dispersion: float,
        eps_revision: float
    ) -> dict:
        sig_ivp = max(0.0, (iv_percentile - self.min_ivp) / (100.0 - self.min_ivp))
        sig_em_ratio = max(0.0, (implied_em / hist_avg_em - 1.0) / 0.5)  # Normalize
        sig_analyst = np.clip(analyst_dispersion / 0.05, 0.0, 1.0)       # High dispersion = more uncertainty
        sig_eps_rev = np.clip(abs(eps_revision) / 0.10, 0.0, 1.0)         # Large EPS revision

        # Composite signal
        weights = [0.35, 0.35, 0.15, 0.15]
        signal = np.dot(weights, [sig_ivp, sig_em_ratio, sig_analyst, sig_eps_rev])

        # Direction: short vol if signal is from overpricing
        if implied_em > self.min_em_ratio * hist_avg_em and iv_percentile > self.min_ivp:
            direction = 'short'
        else:
            direction = 'long'

        return {
            'ticker': ticker,
            'signal_strength': signal,
            'direction': direction,
            'sig_ivp': sig_ivp,
            'sig_em_ratio': sig_em_ratio,
            'sig_analyst': sig_analyst,
            'sig_eps_rev': sig_eps_rev
        }

    def portfolio_optimize(
        self, signals: List[dict], expected_pnl: np.ndarray,
        pnl_cov: np.ndarray, vega_per_unit: np.ndarray
    ) -> np.ndarray:
        """
        Mean-variance portfolio optimization for event vol trades.
        """
        n = len(signals)

        def objective(x):
            port_var = x @ pnl_cov @ x
            port_ret = x @ expected_pnl
            return port_var - 2.0 * port_ret  # Minimize variance - 2 * return

        def grad(x):
            return 2 * pnl_cov @ x - 2 * expected_pnl

        # Constraints
        constraints = [
            # Gross vega limit
            {'type': 'ineq', 'fun': lambda x: self.gross_vega_limit - np.abs(x @ vega_per_unit)}
        ]

        # Bounds: individual position limit
        bounds = [
            (-self.max_single_vega / vega_per_unit[i], self.max_single_vega / vega_per_unit[i])
            for i in range(n)
        ]

        signal_strengths = np.array([s['signal_strength'] for s in signals])
        x0 = (signal_strengths / max(signal_strengths.sum(), 1e-6)) * (self.gross_vega_limit / vega_per_unit.mean())

        result = minimize(
            objective, x0, jac=grad, method='SLSQP',
            bounds=bounds, constraints=constraints,
            options={'ftol': 1e-9, 'maxiter': 1000}
        )

        return result.x if result.success else x0

    def compute_portfolio_greeks(self, positions: np.ndarray, greeks_data: pd.DataFrame) -> dict:
        port_delta = np.sum(positions * greeks_data['delta'] * greeks_data['spot'])
        port_gamma = np.sum(positions * greeks_data['gamma'] * (greeks_data['spot']**2) / 100.0)
        port_vega = np.sum(positions * greeks_data['vega'])
        port_theta = np.sum(positions * greeks_data['theta'])

        return {
            'dollar_delta': port_delta,
            'dollar_gamma': port_gamma,
            'dollar_vega': port_vega,
            'daily_theta': port_theta,
            'theta_vega_ratio': port_theta / max(abs(port_vega), 1e-6),
            'n_positions': np.sum(np.abs(positions) > 0.0)
        }

    def stress_test(
        self, positions: np.ndarray, straddle_prices: np.ndarray,
        strikes: np.ndarray, spots: np.ndarray, scenarios: dict = None
    ) -> pd.DataFrame:
        if scenarios is None:
            scenarios = {
                '3x_EM_gap': {'move_mult': 3.0, 'vol_mult': 1.5},
                '2x_EM_gap': {'move_mult': 2.0, 'vol_mult': 1.3},
                'Normal_crush': {'move_mult': 0.8, 'vol_mult': 0.6},
                'No_crush': {'move_mult': 1.0, 'vol_mult': 1.0},
                'Reverse_crush': {'move_mult': 1.5, 'vol_mult': 1.2},
            }

        results = []
        em_pct = straddle_prices / spots  # Implied EM %

        for scenario_name, params in scenarios.items():
            # Simulate portfolio P&L
            moves = em_pct * params['move_mult'] * np.sign(np.random.randn(len(spots)))
            intrinsic_loss = np.abs(moves) * spots
            vol_crush_gain = straddle_prices * (1 - params['vol_mult'])

            # Net P&L for short straddle portfolio
            pnl_per_pos = (straddle_prices - intrinsic_loss) * (1.0 - params['vol_mult'])
            total_pnl = np.sum(positions * pnl_per_pos * 100.0)  # * 100 multiplier

            results.append({
                'scenario': scenario_name,
                'total_pnl': total_pnl,
                'pnl_per_trade': total_pnl / max(np.sum(np.abs(positions) > 0.0), 1)
            })

        return pd.DataFrame(results)

    def kelly_position_size(self, win_prob: float, avg_win: float, avg_loss: float) -> float:
        b = avg_win / abs(avg_loss)
        kelly_full = (win_prob * b - (1.0 - win_prob)) / b
        return max(0.0, kelly_full * self.kelly_fraction)


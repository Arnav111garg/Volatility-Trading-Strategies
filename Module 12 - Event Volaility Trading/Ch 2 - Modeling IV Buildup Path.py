import numpy as np
import matplotlib.pyplot as plt

def iv_path_model(sigma_c: float, sigma_J: float, t_expiry: float, t_event: float, t_grid: np.ndarray) -> np.ndarray:
    iv = np.zeros_like(t_grid)
    for i, t in enumerate(t_grid):
        T_remaining = t_expiry - t
        if T_remaining <= 0:
            iv[i] = np.nan
            continue

        total_var = sigma_c**2 * T_remaining
        if t < t_event:
            total_var += sigma_J**2

        iv[i] = np.sqrt(total_var / T_remaining)

    return iv

def plot_iv_buildup(sigma_c=0.20, sigma_J=0.05):
    t_event = 25/252  # 25 trading days ~ 1 month
    t_expiry = 26/252  # Option expiring 1 day after event

    t_grid = np.linspace(0, t_event - 0.001, 300)  # From now until just before event

    iv = iv_path_model(sigma_c, sigma_J, t_expiry, t_event, t_grid)
    days_remaining = (t_event - t_grid) * 252

    # Expected move in percentage terms
    T_remain = t_expiry - t_grid
    em = spot_proxy = 0.7979 * sigma_J  # Just show event EM as reference

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))

    # Plot 1: IV Path
    ax1 = axes[0]
    ax1.plot(days_remaining, iv * 100, 'b-', linewidth=2.5, label='Earnings-spanning IV')
    ax1.axhline(sigma_c * 100, color='gray', linestyle='--', linewidth=1.5, label=f'Continuous vol ({sigma_c * 100:.0f}%)')
    ax1.set_xlabel('Trading Days Until Earnings')
    ax1.set_ylabel('Implied Volatility (%)')
    ax1.set_title('Pre-Event IV Buildup')
    ax1.invert_xaxis()
    ax1.legend()
    ax1.grid(True, alpha=0.3)

    # Plot 2: Calendar spread
    t_expiry2 = 50/252  # 2-month option
    iv2 = iv_path_model(sigma_c, sigma_J, t_expiry2, t_event, t_grid)
    cal_spread = iv - iv2

    ax2 = axes[1]
    ax2.plot(days_remaining, cal_spread * 100, 'r-', linewidth=2.5)
    ax2.axhline(0, color='gray', linestyle='-', linewidth=0.8)
    ax2.set_xlabel('Trading Days Until Earnings')
    ax2.set_ylabel('Calendar Spread (1m-2m IV, vol pts)')
    ax2.set_title('Calendar Spread Widening Pre-Earnings')
    ax2.invert_xaxis()
    ax2.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig('iv_buildup.png', dpi=150, bbox_inches='tight')
    plt.show()

    return iv, days_remaining

iv, days = plot_iv_buildup(sigma_c=0.20, sigma_J=0.05)


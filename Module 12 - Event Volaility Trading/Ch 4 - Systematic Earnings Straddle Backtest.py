import numpy as np
import pandas as pd
from scipy.stats import norm
from dataclasses import dataclass
from typing import List, Optional

@dataclass
class StraddleTrade:
    ticker: str
    entry_date: str
    earnings_date: str
    expiry_date: str
    strike: float
    spot_entry: float
    straddle_premium: float
    iv_entry: float
    direction: str  # 'long' or 'short'
    spot_exit: float
    straddle_exit: float
    iv_exit: float
    pnl: float
    pnl_pct: float
    event_move: float
    em_implied: float

class EarningsStraddleStrategy:
    """
    Systematic earnings straddle strategy with full P&L attribution.
    """
    def __init__(
        self,
        direction: str = 'short',
        em_threshold: float = 1.2,  # Sell when implied EM > 1.2x hist avg
        hold_days_before: int = 1,  # Enter N days before earnings
        position_size: float = 1000  # $ vega per trade
    ):
        self.direction = direction
        self.em_threshold = em_threshold
        self.hold_days_before = hold_days_before
        self.position_size = position_size
        self.trades_: List[StraddleTrade] = []

    def straddle_price_bs(self, S, K, T, sigma):
        """BSM straddle price."""
        if T <= 0:
            return abs(S - K)
        d1 = (np.log(S / K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        call = S * norm.cdf(d1) - K * norm.cdf(d2)
        put = K - S + call  # PCP (r=0)
        return call + put

    def straddle_vega(self, S, K, T, sigma):
        """Straddle vega (per 1% IV move)."""
        if T <= 0:
            return 0.0
        d1 = (np.log(S / K) + 0.5 * sigma**2 * T) / (sigma * np.sqrt(T))
        return 2.0 * S * norm.pdf(d1) * np.sqrt(T) / 100.0

    def should_trade(self, implied_em: float, hist_avg_em: float) -> bool:
        """
        Signal filter: trade when implied EM > threshold * historical average.
        For short strategy: only sell when IV is elevated.
        """
        if self.direction == 'short':
            return implied_em > self.em_threshold * hist_avg_em
        else:  # long
            return implied_em < (1.0 / self.em_threshold) * hist_avg_em

    def execute_trade(
        self, ticker, entry_date, earnings_date, expiry_date,
        spot, strike, iv_pre, sigma_post, actual_move, hist_avg_em=None
    ) -> Optional[StraddleTrade]:
        """
        Execute a single straddle trade.
        """
        T_entry = 5/252  # 1 week to expiry at entry
        T_exit = 2/252   # ~2 days remaining after earnings

        # Entry straddle price
        straddle_entry = self.straddle_price_bs(spot, strike, T_entry, iv_pre)
        em_implied = straddle_entry / spot

        # Check signal
        if hist_avg_em and not self.should_trade(em_implied, hist_avg_em):
            return None  # No trade

        # Compute number of contracts for $position_size vega
        vega_per = self.straddle_vega(spot, strike, T_entry, iv_pre)
        n_contracts = int(self.position_size / max(vega_per, 1e-6))

        # Exit after earnings
        spot_exit = spot * (1.0 + actual_move)
        straddle_exit = self.straddle_price_bs(spot_exit, strike, T_exit, sigma_post)

        # P&L
        if self.direction == 'short':
            pnl_per = (straddle_entry - straddle_exit) * 100.0  # per contract (100x)
        else:
            pnl_per = (straddle_exit - straddle_entry) * 100.0

        total_pnl = pnl_per * n_contracts
        pnl_pct = (straddle_exit - straddle_entry) / straddle_entry
        if self.direction == 'short':
            pnl_pct = -pnl_pct

        trade = StraddleTrade(
            ticker=ticker,
            entry_date=entry_date,
            earnings_date=earnings_date,
            expiry_date=expiry_date,
            strike=strike,
            spot_entry=spot,
            straddle_premium=straddle_entry,
            iv_entry=iv_pre,
            direction=self.direction,
            spot_exit=spot_exit,
            straddle_exit=straddle_exit,
            iv_exit=sigma_post,
            pnl=total_pnl,
            pnl_pct=pnl_pct,
            event_move=actual_move,
            em_implied=em_implied
        )
        self.trades_.append(trade)
        return trade

    def portfolio_stats(self) -> pd.Series:
        if not self.trades_:
            return pd.Series()

        df = pd.DataFrame([t.__dict__ for t in self.trades_])
        cumsum_pnl = df['pnl'].cumsum()
        cummax_pnl = cumsum_pnl.cummax()

        return pd.Series({
            'n_trades': len(df),
            'win_rate': (df['pnl'] > 0).mean(),
            'avg_pnl': df['pnl'].mean(),
            'total_pnl': df['pnl'].sum(),
            'avg_pnl_pct': df['pnl_pct'].mean(),
            'sharpe': df['pnl_pct'].mean() / df['pnl_pct'].std() if df['pnl_pct'].std() > 0 else 0.0,
            'max_drawdown': (cumsum_pnl - cummax_pnl).min(),
            'avg_implied_em': df['em_implied'].mean(),
            'avg_realized_em': df['event_move'].abs().mean(),
            'overpricing_ratio': df['em_implied'].mean() / df['event_move'].abs().mean()
        })

# ---- Simulation ----
np.random.seed(0)
N = 200
strategy = EarningsStraddleStrategy(direction='short', em_threshold=1.0)

for i in range(N):
    spot = 100.0
    iv_pre = np.random.uniform(0.35, 0.65)  # Event-period IV
    sig_j = np.random.uniform(0.03, 0.06)   # Actual jump vol
    act_mv = np.random.normal(0, sig_j)     # Actual move
    sig_pst = np.random.uniform(0.18, 0.28)  # Post-event continuous IV

    strategy.execute_trade(
        ticker=f'SIM_{i:03d}',
        entry_date=f'2020-{(i % 12) + 1:02d}-01',
        earnings_date=f'2020-{(i % 12) + 1:02d}-15',
        expiry_date=f'2020-{(i % 12) + 1:02d}-22',
        spot=spot,
        strike=spot,
        iv_pre=iv_pre,
        sigma_post=sig_pst,
        actual_move=act_mv,
        hist_avg_em=0.04
    )

stats = strategy.portfolio_stats()
print("\n=== Earnings Straddle Strategy Statistics ===")
for k, v in stats.items():
    print(f" {k:30s}: {v:.4f}")


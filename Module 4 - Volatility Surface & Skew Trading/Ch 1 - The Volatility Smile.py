  S, T, r, q = 4500, 0.083, 0.05, 0.015
  F = S * np.exp((r-q)*T)
  strikes = np.arange(3800, 5200, 50)
  true_ivs = 0.22 - 0.5*np.log(strikes/F) + 0.8*np.log(strikes/F)**2
  prices = [bs_call(S, K, T, r, q, iv) for K, iv in zip(strikes, true_ivs)]
  recovered_ivs = compute_smile(S, T, r, q, strikes, prices)
  max_error = np.nanmax(np.abs(recovered_ivs - true_ivs))
  print(f"Max IV recovery error: {max_error:.2e}")


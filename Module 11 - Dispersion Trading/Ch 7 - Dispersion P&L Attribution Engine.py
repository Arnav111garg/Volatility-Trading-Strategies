import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import norm
from dataclasses import dataclass, field
from typing import Optional

@dataclass
class DispersionPosition:
    """ Represents a dispersion trade position. """
    weights: np.ndarray             # Constituent weights
    stock_ivols_init: np.ndarray     # Initial single-stock implied vols
    idx_ivol_init: float             # Initial index implied vol
    notional_vega: float             # Index vega notional ($)
    maturity_days: int               # Total trade duration in trading days
    theta_weights: Optional[np.ndarray] = None  # Dispersion weights

    def __post_init__(self):
        self.weights = self.weights / self.weights.sum()
        self.N = len(self.weights)
        self.T = self.maturity_days / 252

        if self.theta_weights is None:
            # Vega-weighted
            self.theta_weights = (self.weights * self.stock_ivols_init / self.idx_ivol_init)

        # Variance swap strikes (ATM implied vol)
        self.strike_idx = self.idx_ivol_init
        self.strikes_stk = self.stock_ivols_init.copy()

        # Notionals per leg
        self.notional_idx = self.notional_vega
        self.notionals_stk = self.theta_weights * self.notional_vega

    @property
    def sigma_w_bar(self):
        return np.dot(self.weights, self.stock_ivols_init)

    @property
    def var_avg_init(self):
        return np.dot(self.weights ** 2, self.stock_ivols_init ** 2)

    @property
    def implied_corr_init(self):
        num = self.idx_ivol_init ** 2 - self.var_avg_init
        den = self.sigma_w_bar ** 2 - self.var_avg_init
        return num / den if den > 1e-10 else np.nan


class DispersionPnLEngine:
    def __init__(self, position: DispersionPosition):
        self.pos = position

    def compute_realized_stats(self, stock_price_paths: np.ndarray, idx_price_path: np.ndarray) -> dict:
        """
        Compute realized vols, realized correlation, and PnL.
        """
        N, T_plus1 = stock_price_paths.shape
        T = T_plus1 - 1

        # Compute log returns
        log_ret_stocks = np.diff(np.log(stock_price_paths), axis=1)
        log_ret_idx = np.diff(np.log(idx_price_path))

        # Annualized realized variance
        ann_factor = 252
        real_var_stocks = np.mean(log_ret_stocks ** 2, axis=1) * ann_factor
        real_var_idx = np.mean(log_ret_idx ** 2) * ann_factor
        real_vol_stocks = np.sqrt(real_var_stocks)
        real_vol_idx = np.sqrt(real_var_idx)

        # Realized correlation matrix
        corr_mat = np.corrcoef(log_ret_stocks)
        avg_pairwise_corr = (corr_mat.sum() - N) / (N * (N - 1))

        # Implied (effective) realized correlation
        w = self.pos.weights
        swbar_real = np.dot(w, real_vol_stocks)
        varavg_real = np.dot(w ** 2, real_var_stocks)
        denom = swbar_real ** 2 - varavg_real
        real_implied_corr = (real_var_idx - varavg_real) / denom if denom > 1e-10 else np.nan

        return {
            'real_var_stocks': real_var_stocks,
            'real_vol_stocks': real_vol_stocks,
            'real_var_idx': real_var_idx,
            'real_vol_idx': real_vol_idx,
            'corr_matrix': corr_mat,
            'avg_pairwise_corr': avg_pairwise_corr,
            'real_implied_corr': real_implied_corr,
            'sigma_w_bar_real': swbar_real,
        }

    def terminal_pnl(self, realized_stats: dict) -> dict:
        """
        Compute and attribute terminal P&L.
        """
        pos = self.pos
        rs = realized_stats

        # Leg P&Ls
        pnl_idx = -pos.notional_idx * (rs['real_var_idx'] - pos.strike_idx ** 2)
        pnl_stk = np.sum(pos.notionals_stk * (rs['real_var_stocks'] - pos.strikes_stk ** 2))
        total_pnl = pnl_idx + pnl_stk

        # Attribution
        init_corr = pos.implied_corr_init
        real_corr = rs['real_implied_corr']

        corr_vega = pos.notional_idx * (pos.sigma_w_bar ** 2 - pos.var_avg_init)
        corr_pnl = corr_vega * (init_corr - real_corr)

        vol_pnl_stk = np.sum(pos.notionals_stk * (rs['real_var_stocks'] - pos.strikes_stk ** 2))
        vol_pnl_idx = -pos.notional_idx * (rs['real_var_idx'] - pos.strike_idx ** 2)

        return {
            'total_pnl': total_pnl,
            'pnl_index_leg': pnl_idx,
            'pnl_stock_legs': pnl_stk,
            'corr_pnl_attributed': corr_pnl,
            'initial_implied_corr': init_corr,
            'realized_implied_corr': real_corr,
            'corr_risk_premium_earned': init_corr - real_corr,
            'vol_premium_index': pos.strike_idx ** 2 - rs['real_var_idx'],
            'vol_premium_avg_stock': np.mean(pos.strikes_stk ** 2 - rs['real_var_stocks']),
        }

    def daily_pnl_path(self, stock_price_paths: np.ndarray, idx_price_path: np.ndarray, daily_ivols: np.ndarray = None) -> pd.DataFrame:
        """
        Compute day-by-day P&L path (mark-to-market).
        """
        N, T_plus1 = stock_price_paths.shape
        T = T_plus1 - 1
        pos = self.pos

        daily_records = []

        # Accumulated realized variance
        accum_var_stk = np.zeros(N)
        accum_var_idx = 0.0

        # Current MTM implied vols
        if daily_ivols is None:
            curr_ivols_stk = pos.stock_ivols_init.copy()
            curr_ivol_idx = pos.idx_ivol_init

        for t in range(T):
            # Realized return for day t
            ret_stk = np.log(stock_price_paths[:, t + 1] / stock_price_paths[:, t])
            ret_idx = np.log(idx_price_path[t + 1] / idx_price_path[t])

            # Accumulate
            accum_var_stk += ret_stk ** 2 * 252
            accum_var_idx += ret_idx ** 2 * 252

            # Realized variance contribution today
            daily_real_var_stk = ret_stk ** 2 * 252
            daily_real_var_idx = ret_idx ** 2 * 252

            # Remaining time weight
            t_elapsed = (t + 1) / T
            t_remain = 1 - t_elapsed

            # Today's implied vols
            if daily_ivols is not None:
                new_ivols_stk = daily_ivols[:N, t + 1]
                new_ivol_idx = daily_ivols[N, t + 1]
            else:
                new_ivols_stk = curr_ivols_stk * (1 + 0.02 * np.random.randn(N))
                new_ivol_idx = curr_ivol_idx * (1 + 0.02 * np.random.randn())

            new_ivols_stk = np.clip(new_ivols_stk, 0.05, 1.5)
            new_ivol_idx = np.clip(new_ivol_idx, 0.05, 1.5)

            # MTM P&L components:
            pnl_real_stk = np.sum(pos.notionals_stk * daily_real_var_stk / T)
            pnl_real_idx = -pos.notional_idx * daily_real_var_idx / T

            pnl_vega_stk = np.sum(pos.notionals_stk * t_remain * (new_ivols_stk ** 2 - curr_ivols_stk ** 2))
            pnl_vega_idx = -pos.notional_idx * t_remain * (new_ivol_idx ** 2 - curr_ivol_idx ** 2)

            total_daily = pnl_real_stk + pnl_real_idx + pnl_vega_stk + pnl_vega_idx

            curr_ivols_stk = new_ivols_stk
            curr_ivol_idx = new_ivol_idx

            daily_records.append({
                'day': t,
                'pnl_real_stk': pnl_real_stk,
                'pnl_real_idx': pnl_real_idx,
                'pnl_vega_stk': pnl_vega_stk,
                'pnl_vega_idx': pnl_vega_idx,
                'total_daily': total_daily,
                'idx_ivol': curr_ivol_idx,
                'avg_stk_ivol': curr_ivols_stk.mean(),
            })

        df = pd.DataFrame(daily_records)
        df['cum_pnl'] = df['total_daily'].cumsum()
        return df


# =================== SIMULATION DEMO ===================
np.random.seed(12)
N = 5
T_days = 63

weights = np.array([0.30, 0.25, 0.20, 0.15, 0.10])
stk_ivols = np.array([0.28, 0.32, 0.25, 0.30, 0.35])
idx_ivol = 0.20
notional = 10_000_000

pos = DispersionPosition(weights, stk_ivols, idx_ivol, notional, T_days)
print(f"Trade Setup:")
print(f"Implied correlation: {pos.implied_corr_init:.3f}")
print(f"Weighted avg stock vol: {pos.sigma_w_bar:.2%}")
print(f"Index implied vol: {pos.idx_ivol_init:.2%}")

rho_realized = 0.15
C = rho_realized * np.ones((N, N))
np.fill_diagonal(C, 1.0)
real_vols = stk_ivols * 0.85
Sigma = np.outer(real_vols, real_vols) * C
L = np.linalg.cholesky(Sigma)

T = T_days
stock_paths = np.zeros((N, T + 1))
stock_paths[:, 0] = 100.0
idx_path = np.zeros(T + 1)
idx_path[0] = 100.0

for t in range(1, T + 1):
    eps = np.random.randn(N)
    drets = L @ eps / np.sqrt(252)
    stock_paths[:, t] = stock_paths[:, t - 1] * np.exp(drets)
    idx_path[t] = np.dot(weights, stock_paths[:, t] / stock_paths[:, 0]) * 100

engine = DispersionPnLEngine(pos)
rs = engine.compute_realized_stats(stock_paths, idx_path)
pnl_attr = engine.terminal_pnl(rs)

print(f"\nP&L Attribution:")
for k, v in pnl_attr.items():
    if isinstance(v, float):
        if 'pnl' in k or 'premium' in k:
            print(f"  {k:<35}: ${v:>12,.0f}")
        else:
            print(f"  {k:<35}: {v:.4f}")

daily_df = engine.daily_pnl_path(stock_paths, idx_path)

fig, axes = plt.subplots(2, 2, figsize=(14, 8))

axes[0, 0].plot(daily_df['cum_pnl'] / 1e6, color='navy', lw=2.5, label='Cumulative P&L')

import numpy as np
import pandas as pd
from scipy.optimize import minimize_scalar
import matplotlib.pyplot as plt

class DispersionRiskManager:
    """
    Computes risk metrics for a dispersion book.
    """
    def __init__(self, weights, vols_impl, idx_ivol, notional_idx, notional_stocks):
        self.w = np.array(weights)
        self.v = np.array(vols_impl)
        self.sig_I = idx_ivol
        self.N_I = notional_idx
        self.N_s = np.array(notional_stocks)
        self.N = len(weights)

    @property
    def sigma_w_bar(self):
        """ Weighted average single-stock vol."""
        return np.dot(self.w, self.v)

    @property
    def var_avg(self):
        """ Weighted average of single-stock variances."""
        return np.dot(self.w ** 2, self.v ** 2)

    def pnl_at_maturity(self, realized_vols, realized_corr, strikes_stocks, strike_idx):
        # Index variance from realized vols + corr (equicorrelation)
        var_idx_real = (
            (1 - realized_corr) * np.sum(self.w ** 2 * realized_vols ** 2) +
            realized_corr * np.dot(self.w, realized_vols) ** 2
        )

        # PnL from individual legs
        pnl_idx = -self.N_I * (var_idx_real - strike_idx ** 2)  # short
        pnl_stocks = np.sum(self.N_s * (realized_vols ** 2 - strikes_stocks ** 2))  # long

        return {
            'pnl_index_leg': pnl_idx,
            'pnl_stock_legs': pnl_stocks,
            'total_pnl': pnl_idx + pnl_stocks,
            'realized_idx_vol': np.sqrt(var_idx_real),
            'realized_avg_corr': realized_corr,
        }

    def greco(self):
        """ Correlation sensitivity (dPnL / d_rho)."""
        # dVar_I / d_rho = sigma_w_bar^2 - VarAvg
        dvar_drho = self.sigma_w_bar ** 2 - self.var_avg
        return -self.N_I * dvar_drho  # negative for short-corr trade

    def stress_test_correlation(self, corr_scenarios, current_corr, real_stock_vols=None):
        """
        Stress test PnL across correlation scenarios.
        """
        if real_stock_vols is None:
            real_stock_vols = self.v  # assume vols unchanged
        strikes_s = self.v  # var swap struck at current implied vol
        strike_I = self.sig_I

        results = []
        for rho in corr_scenarios:
            pnl = self.pnl_at_maturity(real_stock_vols, rho, strikes_s, strike_I)
            results.append({'corr': rho, **pnl})

        return pd.DataFrame(results)

# ---- Example ----
N = 5
weights = np.array([0.25, 0.20, 0.20, 0.20, 0.15])
stock_ivols = np.array([0.28, 0.32, 0.25, 0.30, 0.35])
idx_ivol = 0.20

# Equicorrelation implied corr
sigma_wb = np.dot(weights, stock_ivols)
var_avg = np.dot(weights ** 2, stock_ivols ** 2)
impl_corr = (idx_ivol ** 2 - var_avg) / (sigma_wb ** 2 - var_avg)
print(f"Implied correlation: {impl_corr:.3f}")

# Notionals: $100M index, vega-weighted stocks
N_idx = 100_000_000
N_stocks = weights * (stock_ivols / idx_ivol) * N_idx

rm = DispersionRiskManager(weights, stock_ivols, idx_ivol, N_idx, N_stocks)

print(f"\nGreco (dPnL / d_rho): ${rm.greco():,.0f}")
print(f"-> 1% rise in corr ~ ${rm.greco() * 0.01:,.0f} P&L impact")

# Stress test
corr_range = np.linspace(0.05, 0.95, 50)
stress_df = rm.stress_test_correlation(corr_range, impl_corr)

fig, axes = plt.subplots(1, 2, figsize=(14, 5))
axes[0].plot(stress_df['corr'] * 100, stress_df['total_pnl'] / 1e6, color='navy', lw=2.5)
axes[0].axhline(0, color='black', lw=1)
axes[0].axvline(impl_corr * 100, color='crimson', ls='--', lw=1.8, label=f'Impl. corr = {impl_corr:.2f}')
axes[0].fill_between(stress_df['corr'] * 100, stress_df['total_pnl'] / 1e6,
                     where=stress_df['total_pnl'] > 0, alpha=0.25, color='green', label='Profitable')
axes[0].fill_between(stress_df['corr'] * 100, stress_df['total_pnl'] / 1e6,
                     where=stress_df['total_pnl'] <= 0, alpha=0.25, color='red', label='Loss')
axes[0].set_xlabel('Realized Correlation (%)', fontsize=12)
axes[0].set_ylabel('P&L ($M)', fontsize=12)
axes[0].set_title('Dispersion Trade P&L vs. Realized Correlation', fontsize=13)
axes[0].legend(fontsize=11)
axes[0].grid(True, alpha=0.3)

# Decomposed PnL
axes[1].plot(stress_df['corr'] * 100, stress_df['pnl_index_leg'] / 1e6, color='crimson', lw=2, label='Index leg (short)')
axes[1].plot(stress_df['corr'] * 100, stress_df['pnl_stock_legs'] / 1e6, color='teal', lw=2, label='Stock legs (long)')
axes[1].plot(stress_df['corr'] * 100, stress_df['total_pnl'] / 1e6, color='navy', lw=2.5, ls='--', label='Total')
axes[1].axhline(0, color='black', lw=1)
axes[1].set_xlabel('Realized Correlation (%)', fontsize=12)
axes[1].set_ylabel('P&L ($M)', fontsize=12)
axes[1].set_title('P&L Decomposition: Index vs. Stock Legs', fontsize=13)
axes[1].legend(fontsize=11)
axes[1].grid(True, alpha=0.3)

plt.tight_layout()

import numpy as np
from scipy.stats import norm
from scipy.integrate import quad
import matplotlib.pyplot as plt

def bs_price(S, K, T, r, sigma, option_type='call'):
    """Black-Scholes option price."""
    d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    if option_type == 'call':
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

def log_strip_fair_variance(S0, r, T, sigma_func, n_strikes=500):
    F = S0 * np.exp(r * T)

    # Integration bounds: far OTM options
    K_low = F * 0.3   # 70% OTM put
    K_high = F * 3.0  # 200% OTM call

    def put_integrand(K):
        sig = sigma_func(K)
        p = bs_price(S0, K, T, r, sig, 'put')
        return p / K ** 2

    def call_integrand(K):
        sig = sigma_func(K)
        c = bs_price(S0, K, T, r, sig, 'call')
        return c / K ** 2

    # Numerical integration
    put_integral, _ = quad(put_integrand, K_low, F, limit=200)
    call_integral, _ = quad(call_integrand, F, K_high, limit=200)

    fair_var = (2 * np.exp(r * T) / T) * (put_integral + call_integral)
    return fair_var

# ---- Example : Flat vol surface ----
S0, r, T = 100.0, 0.05, 0.25  # 3-month
sigma_flat = 0.25

def flat_surface(K):
    return sigma_flat

var_logstrip = log_strip_fair_variance(S0, r, T, flat_surface)
print(f"Flat vol: {sigma_flat:.1%}")
print(f"Log-strip fair var: {var_logstrip:.6f}")
print(f"Implied vol (sqrt): {np.sqrt(var_logstrip):.4%}")
print(f"Difference (bps): {abs(np.sqrt(var_logstrip) - sigma_flat) * 10000:.2f}")

# ---- Example : SABR-like skew ----
def skewed_surface(K):
    """Simple linear skew : lower strike = higher vol."""
    atm_vol = 0.20
    skew_slope = -0.10 / S0  # -10 vol pts per 100% move down
    return max(atm_vol + skew_slope * (K - S0), 0.05)

var_skew = log_strip_fair_variance(S0, r, T, skewed_surface)
print(f"\nSkewed surface:")
print(f"ATM vol: {skewed_surface(S0):.1%}")
print(f"Log-strip fair var: {var_skew:.6f}")
print(f"Implied vol (sqrt): {np.sqrt(var_skew):.4%}")
print(f"Convexity premium: {(np.sqrt(var_skew) - skewed_surface(S0)) * 10000:.1f} bps")

# ---- Plot : Option weights across strikes ----
strikes = np.linspace(60, 180, 500)

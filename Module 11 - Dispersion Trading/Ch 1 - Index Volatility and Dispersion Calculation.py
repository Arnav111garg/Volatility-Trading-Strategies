import numpy as np
import matplotlib.pyplot as plt
from scipy.linalg import cholesky

# ---- Two - Stock Example ----
def index_vol_2stock(w1, w2, sig1, sig2, rho):
    """ Compute index volatility for a 2-stock index. """
    var_idx = (w1 * sig1)**2 + (w2 * sig2)**2 + 2 * w1 * w2 * sig1 * sig2 * rho
    return np.sqrt(var_idx)

w1, w2 = 0.6, 0.4
sig1, sig2 = 0.25, 0.30
rho = 0.5

sigma_I = index_vol_2stock(w1, w2, sig1, sig2, rho)
sigma_wbar = w1 * sig1 + w2 * sig2
dispersion = sigma_wbar - sigma_I

print(f"Index Volatility: {sigma_I:.4%}")
print(f"Weighted Average Vol: {sigma_wbar:.4%}")
print(f"Dispersion: {dispersion:.4%}")
print(f"Dispersion >= 0: {dispersion >= 0}")

# ---- Generalized N-Stock Version ----
def index_vol_general(weights, vols, corr_matrix):
    w = np.array(weights)
    v = np.array(vols)
    C = np.array(corr_matrix)

    # Covariance matrix
    Sigma = np.outer(v, v) * C

    # Index variance
    idx_var = w @ Sigma @ w
    return np.sqrt(idx_var)

# ---- Plot sigma_I vs rho ----
rhos = np.linspace(-1, 1, 300)
sigma_Is = [index_vol_2stock(w1, w2, sig1, sig2, r) for r in rhos]

fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# Left: sigma_I vs rho
axes[0].plot(rhos, [s * 100 for s in sigma_Is], color='navy', lw=2.5, label=r'$\sigma_I(\rho)$')
axes[0].axhline(sigma_wbar * 100, color='crimson', ls='--', lw=1.8, label=r'$\bar{\sigma}_w = 27\%$')
axes[0].axvline(0.5, color='gray', ls=':', lw=1.5, label=r'$\rho = 0.5$')
axes[0].scatter([0.5], [sigma_I * 100], color='orange', zorder=5, s=80)
axes[0].set_xlabel(r'Pairwise Correlation $\rho_{12}$', fontsize=12)
axes[0].set_ylabel('Volatility (%)', fontsize=12)
axes[0].set_title(r'Index Vol $\sigma_I$ vs Correlation', fontsize=13)
axes[0].legend(fontsize=11)
axes[0].grid(True, alpha=0.3)

# Right: Dispersion vs rho
dispersions = [(sigma_wbar - s) * 100 for s in sigma_Is]
axes[1].fill_between(rhos, dispersions, alpha=0.3, color='teal')
axes[1].plot(rhos, dispersions, color='teal', lw=2.5, label=r'Dispersion $\mathcal{D}(\rho)$')
axes[1].axvline(0.5, color='gray', ls=':', lw=1.5)
axes[1].set_xlabel(r'Pairwise Correlation $\rho_{12}$', fontsize=12)
axes[1].set_ylabel('Dispersion (vol pts)', fontsize=12)
axes[1].set_title(r'Dispersion $\mathcal{D} = \bar{\sigma}_w - \sigma_I$ vs Correlation', fontsize=13)
axes[1].legend(fontsize=11)
axes[1].grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('index_vol_dispersion.pdf', dpi=200, bbox_inches='tight')
plt.show()


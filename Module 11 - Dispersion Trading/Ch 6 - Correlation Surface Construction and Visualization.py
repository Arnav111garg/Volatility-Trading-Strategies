import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D
from scipy.interpolate import RectBivariateSpline
from scipy.optimize import curve_fit

class CorrelationSurface:
    """
    Builds and analyzes the implied correlation surface
    across moneyness and maturity.
    """
    def __init__(self, weights: np.ndarray, stock_names: list = None):
        self.weights = np.array(weights) / np.sum(weights)
        self.N = len(weights)
        self.stock_names = stock_names or [f'S{i}' for i in range(self.N)]

    def implied_correlation_grid(
        self,
        idx_vol_surface: np.ndarray,
        stock_vol_surfaces: list,
        strikes: np.ndarray,
        maturities: np.ndarray
    ) -> np.ndarray:
        n_K, n_T = len(strikes), len(maturities)
        corr_surface = np.zeros((n_K, n_T))

        for i, K in enumerate(strikes):
            for j, T in enumerate(maturities):
                sig_I = idx_vol_surface[i, j]
                sigs = np.array([sv[i, j] for sv in stock_vol_surfaces])

                w = self.weights
                var_avg = np.sum((w * sigs) ** 2)
                sig_wb = np.sum(w * sigs)
                denom = sig_wb ** 2 - var_avg

                if denom < 1e-10:
                    corr_surface[i, j] = np.nan
                else:
                    corr_surface[i, j] = (sig_I ** 2 - var_avg) / denom

        return np.clip(corr_surface, -1.0, 1.0)

    def fit_parametric_surface(self, corr_surface, strikes, maturities):
        from itertools import product

        K_grid, T_grid = np.meshgrid(strikes, maturities, indexing='ij')

        K_flat = K_grid.flatten()
        T_flat = T_grid.flatten()
        rho_flat = corr_surface.flatten()

        valid = ~np.isnan(rho_flat)
        K_v, T_v, rho_v = K_flat[valid], T_flat[valid], rho_flat[valid]

        def model(X, rho0, a, b, c, d):
            K_, T_ = X
            lnT = np.log(T_)
            return rho0 + a * (K_ - 1) + b * (K_ - 1) ** 2 + c * lnT + d * (K_ - 1) * lnT

        X_data = (K_v, T_v)
        popt, pcov = curve_fit(
            model, X_data, rho_v,
            p0=[0.5, -0.3, 0.1, -0.05, 0.02],
            bounds=([-1, -5, -5, -2, -2], [1, 5, 5, 2, 2])
        )

        return popt, pcov, model

    def plot_surface(self, corr_surface, strikes, maturities, title='Implied Correlation Surface'):
        """3D surface plot of implied correlation."""
        K_grid, T_grid = np.meshgrid(strikes, maturities, indexing='ij')

        fig = plt.figure(figsize=(14, 6))

        # 3D surface
        ax1 = fig.add_subplot(121, projection='3d')
        surf = ax1.plot_surface(
            K_grid, T_grid, corr_surface,
            cmap='RdYlGn_r', alpha=0.9,
            linewidth=0.5, edgecolors='k'
        )
        fig.colorbar(surf, ax=ax1, shrink=0.5, label='Implied Correlation')

        ax1.set_xlabel('Strike (S/F)', fontsize=11)
        ax1.set_ylabel('Maturity (yrs)', fontsize=11)
        ax1.set_zlabel('Impl. Correlation', fontsize=11)
        ax1.set_title(title, fontsize=12)

        # 2D contour
        ax2 = fig.add_subplot(122)
        cs = ax2.contourf(K_grid, T_grid, corr_surface, levels=20, cmap='RdYlGn_r')
        fig.colorbar(cs, ax=ax2, label='Implied Correlation')
        ax2.set_xlabel('Strike (S/F)', fontsize=12)
        ax2.set_ylabel('Maturity (yrs)', fontsize=12)
        ax2.set_title('Correlation Contour Map', fontsize=12)
        ax2.grid(True, alpha=0.3)

        plt.tight_layout()
        plt.savefig('correlation_surface.pdf', dpi=200, bbox_inches='tight')
        return fig

# ---- Construct a Synthetic Correlation Surface ----
N = 5
weights = np.array([0.30, 0.25, 0.20, 0.15, 0.10])
stock_base_vols = np.array([0.28, 0.32, 0.25, 0.30, 0.35])

strikes = np.array([0.70, 0.80, 0.90, 0.95, 1.00, 1.05, 1.10, 1.20])
maturities = np.array([1/12, 2/12, 3/12, 6/12, 1.0, 1.5, 2.0])

# Synthetic index surface : high vol for low strikes / short maturities
def idx_surf_model(K, T):
    atm_vol = 0.20
    skew = -0.25 * (K - 1.0)
    term = 0.02 * np.log(max(T, 0.01))
    return atm_vol + skew + term

# Single-stock surfaces (less skew than index)
def stock_surf_model(base_vol, K, T, skew_factor=0.6):
    skew = -0.15 * skew_factor * (K - 1.0)
    term = 0.015 * np.log(max(T, 0.01))
    return base_vol + skew + term

n_K, n_T = len(strikes), len(maturities)
idx_surf = np.array([[idx_surf_model(K, T) for T in maturities] for K in strikes])
stock_surfs = [
    np.array([[stock_surf_model(bv, K, T) for T in maturities] for K in strikes])
    for bv in stock_base_vols
]

cs_builder = CorrelationSurface(weights)
corr_surf = cs_builder.implied_correlation_grid(idx_surf, stock_surfs, strikes, maturities)

print("Correlation Surface (Strike x Maturity):")
df_surf = pd.DataFrame(corr_surf.round(3), index=strikes, columns=[f'{T:.2f}Y' for T in maturities])
df_surf.index.name = 'Strike'
print(df_surf.to_string())

# Plot
cs_builder.plot_surface(
    corr_surf, strikes, maturities,
    title='Implied Correlation Surface: 5-Stock Index'
)
plt.show()


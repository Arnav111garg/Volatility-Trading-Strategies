import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.colors as mcolors
from sklearn.decomposition import PCA
from scipy.cluster.hierarchy import dendrogram, linkage, fcluster

class CorrelationDecomposer:
    """
    Decomposes a realized correlation matrix into components
    useful for dispersion trading analysis.
    """
    def __init__(self, returns: pd.DataFrame):
        self.returns = returns
        self.N = returns.shape[1]
        self.tickers = returns.columns.tolist()

    def compute_corr_matrix(self, window=252):
        """ Rolling correlation matrix. """
        return self.returns.iloc[-window:].corr()

    def average_pairwise_corr(self, C=None):
        """ Weighted average pairwise correlation. """
        if C is None:
            C = self.compute_corr_matrix()
        # Off-diagonal mean
        mask = np.ones((self.N, self.N), dtype=bool)
        np.fill_diagonal(mask, False)
        return C.values[mask].mean()

    def pca_decomposition(self, C=None):
        """
        PCA decomposition of correlation matrix.
        Returns eigenvalues, eigenvectors, PVE.
        """
        if C is None:
            C = self.compute_corr_matrix()
        eigenvalues, eigenvectors = np.linalg.eigh(C.values)
        # Sort descending
        idx = np.argsort(eigenvalues)[::-1]
        eigenvalues = eigenvalues[idx]
        eigenvectors = eigenvectors[:, idx]

        pve = eigenvalues / eigenvalues.sum()

        return {
            'eigenvalues': eigenvalues,
            'eigenvectors': eigenvectors,
            'pve': pve,
            'cumulative_pve': np.cumsum(pve),
            'n_market_factors': int(np.searchsorted(np.cumsum(pve), 0.5)) + 1
        }

    def equicorrelation_decompose(self, C=None):
        """
        Compute equivalent equicorrelation parameter.
        rho_bar = (avg off-diagonal of C).
        """
        if C is None:
            C = self.compute_corr_matrix()
        rho_bar = self.average_pairwise_corr(C)

        # Reconstruct equicorrelation matrix
        C_eq = rho_bar * np.ones((self.N, self.N))
        np.fill_diagonal(C_eq, 1.0)

        # Residual idiosyncratic component
        C_resid = C.values - C_eq

        return {
            'rho_bar': rho_bar,
            'C_equi': C_eq,
            'C_resid': C_resid,
            'idiosyncratic_frac': np.trace(C_resid) / np.trace(C.values)
        }

    def rolling_average_corr(self, window=63):
        """ Rolling average pairwise correlation. """
        roll_corr = []
        dates = self.returns.index[window:]
        for i in range(window, len(self.returns)):
            C = self.returns.iloc[i - window : i].corr()
            roll_corr.append(self.average_pairwise_corr(C))
        return pd.Series(roll_corr, index=dates, name='AvgCorr')

    def plot_corr_matrix(self, C=None, title='Realized Correlation Matrix'):
        """ Plot heatmap of correlation matrix. """
        if C is None:
            C = self.compute_corr_matrix()
        fig, ax = plt.subplots(figsize=(12, 10))
        cmap = plt.cm.RdBu_r
        norm = mcolors.Normalize(vmin=-0.2, vmax=1.0)
        im = ax.imshow(C.values, cmap=cmap, norm=norm, aspect='auto')

        plt.colorbar(im, ax=ax, shrink=0.8)
        ax.set_title(title, fontsize=14, fontweight='bold')
        ax.set_xlabel('Stock Index', fontsize=12)
        ax.set_ylabel('Stock Index', fontsize=12)
        return fig

# ---- Demonstrate with Synthetic Data ----
np.random.seed(12)
N, T = 50, 504 # 50 stocks, 2 years daily

# Simulate equicorrelated returns: rho = 0.4
rho_true = 0.4
C_true = rho_true * np.ones((N, N))
np.fill_diagonal(C_true, 1.0)
vols = np.random.uniform(0.20, 0.45, N)
Sigma_true = np.outer(vols, vols) * C_true

# Cholesky simulation
L = np.linalg.cholesky(Sigma_true)
eps = np.random.randn(T, N)
returns_mat = (eps @ L.T) / np.sqrt(252) # Daily returns

returns_df = pd.DataFrame(returns_mat, columns=[f'STOCK_{i:02d}' for i in range(N)])
decomposer = CorrelationDecomposer(returns_df)

# PCA
C_realized = decomposer.compute_corr_matrix()
pca_results = decomposer.pca_decomposition(C_realized)
eq_results = decomposer.equicorrelation_decompose(C_realized)

print(f"True equicorrelation: {rho_true:.3f}")
print(f"Estimated avg corr: {eq_results['rho_bar']:.3f}")
print(f"PC1 explains: {pca_results['pve'][0]:.1%} of variance")
print(f"Top 5 PCs explain: {pca_results['cumulative_pve'][4]:.1%} of variance")
print(f"Mkt factor count (50 pct): {pca_results['n_market_factors']} factors")


import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.dates as mdates
from scipy.optimize import minimize
from dataclasses import dataclass, field
from typing import List, Dict, Optional
import warnings
warnings.filterwarnings('ignore')

@dataclass
class DispersionPosition:
    name: str
    weight: float
    theta: float
    ivol: float

@dataclass
class DispersionBookConfig:
    """Configuration for institutional dispersion book."""
    max_names: int = 50
    min_weight_threshold: float = 0.005
    max_single_corr_vega: float = 0.15
    target_corr_vega: float = -1e6
    max_sector_conc: float = 0.30
    roll_freq_days: int = 21
    transaction_cost_idx: float = 0.004
    transaction_cost_stk: float = 0.010
    tenor_days: int = 63

class InstitutionalDispersionBook:
    def __init__(self, config: DispersionBookConfig = None):
        self.config = config or DispersionBookConfig()
        self.positions: List[DispersionPosition] = []
        self.risk_report: Dict = {}
        self.daily_pnl_history: pd.Series = pd.Series(dtype=float)

    def screen_universe(self, weights: np.ndarray,
                        stock_ivols: np.ndarray,
                        sectors: Optional[np.ndarray] = None,
                        names: Optional[List[str]] = None) -> np.ndarray:
        """
        Screen universe for dispersion book eligibility.
        Returns boolean mask of eligible names.
        """
        N = len(weights)
        config = self.config

        eligible = np.ones(N, dtype=bool)

        # 1. Minimum weight threshold
        eligible &= (weights >= config.min_weight_threshold)

        # 2. Sort by weight, take top N names
        if eligible.sum() > config.max_names:
            top_idx = np.argsort(weights)[::-1][:config.max_names]
            mask = np.zeros(N, dtype=bool)
            mask[top_idx] = True
            eligible &= mask

        # 3. Sector concentration check (if sectors provided)
        if sectors is not None:
            unique_sectors = np.unique(sectors[eligible])
            for s in unique_sectors:
                sector_w = weights[eligible & (sectors == s)].sum()
                total_w = weights[eligible].sum()
                if sector_w / total_w > config.max_sector_conc:
                    # Remove smallest-weight names in this sector until limit met
                    sector_names = np.where(eligible & (sectors == s))[0]
                    sector_weights = weights[sector_names]
                    sort_idx = np.argsort(sector_weights)
                    cumulative = 0
                    for idx in sort_idx:
                        cumulative += sector_weights[idx]
                        if sector_w - cumulative <= config.max_sector_conc * total_w:
                            break
                        eligible[sector_names[idx]] = False

        print(f"Universe screening: {eligible.sum()} / {N} names eligible")
        print(f"Weight coverage: {weights[eligible].sum() / weights.sum():.1%}")
        return eligible

    def optimize_weights(self,
                         w_raw: np.ndarray,
                         stock_ivols: np.ndarray,
                         idx_ivol: float,
                         eligible: np.ndarray,
                         scheme: str = 'vega') -> np.ndarray:
        """
        Optimize dispersion position weights.

        Schemes:
        'vega': theta_i = w_i * sig_i / sig_I
        'variance': theta_i = w_i^2
        'optimal': minimize tracking error of correlation exposure
        """
        w = w_raw.copy()
        w[~eligible] = 0
        w /= w.sum() # Renormalize over eligible names

        if scheme == 'vega':
            theta = w * stock_ivols / idx_ivol
        elif scheme == 'variance':
            theta = w ** 2 / (w ** 2).sum()
        elif scheme == 'optimal':
            # Minimize variance of implied correlation estimate
            N = len(w)

            def objective(theta):
                theta = np.abs(theta)
                # Implied corr approximation sensitivity
                sens = theta * stock_ivols ** 2 / idx_ivol
                return np.var(sens) # Minimize heterogeneity

            x0 = w * stock_ivols / idx_ivol
            x0 = x0[eligible]

            res = minimize(
                lambda x: objective(x),
                x0,
                method='SLSQP',
                bounds=[(0, 0.20)] * eligible.sum(),
                constraints={'type': 'eq', 'fun': lambda x: x.sum() - 1.0}
            )
            theta_eligible = np.abs(res.x)
            theta = np.zeros(N)
            theta[eligible] = theta_eligible

        theta[~eligible] = 0
        return theta

    def compute_portfolio_greeks(self,
                                 weights: np.ndarray,
                                 theta: np.ndarray,
                                 stock_ivols: np.ndarray,
                                 idx_ivol: float,
                                 notional: float) -> dict:
        """Compute full Greek profile of the dispersion book."""
        sig_wbar = np.dot(weights, stock_ivols)
        var_avg = np.dot(weights ** 2, stock_ivols ** 2)

        # Implied correlation
        denom = sig_wbar ** 2 - var_avg
        impl_corr = (idx_ivol ** 2 - var_avg) / denom if denom > 1e-10 else np.nan

        # Greco: dPnL / d_rho (overall book)
        greco = -notional * (sig_wbar ** 2 - var_avg)

        # Vega of book (total, by leg)
        vega_idx = -notional * 2 * idx_ivol # Short index vega
        vega_stk = notional * np.sum(theta * 2 * stock_ivols) # Long stock vega
        net_vega = vega_idx + vega_stk

        # Gamma (relative)
        gamma_idx = -notional / (idx_ivol ** 2)
        gamma_stk = notional * np.sum(theta / stock_ivols ** 2)
        net_gamma = gamma_idx + gamma_stk

        # Per-name Greco contribution
        greco_by_name = -notional * theta * (2 * weights * stock_ivols * sig_wbar - 2 * weights ** 2 * stock_ivols ** 2)
        return {
            'implied_corr': impl_corr,
            'greco_total': greco,
            'vega_idx': vega_idx,
            'vega_stk': vega_stk,
            'net_vega': net_vega,
            'gamma_idx': gamma_idx,
            'gamma_stk': gamma_stk,
            'net_gamma': net_gamma,
            'greco_by_name': greco_by_name,
            'corr_vega_ratio': greco / notional,
        }

    def transaction_cost(self,
                         theta_old: np.ndarray,
                         theta_new: np.ndarray,
                         stock_ivols: np.ndarray,
                         idx_ivol_old: float,
                         idx_ivol_new: float,
                         notional: float) -> float:
         """Estimate total transaction cost for rebalance."""
         cfg = self.config

         # Index leg rehedge cost (always happens at roll)
         tc_idx = notional * cfg.transaction_cost_idx * idx_ivol_old

         # Stock leg adjustment costs
         delta_theta = np.abs(theta_new - theta_old)
         tc_stk = notional * np.sum(delta_theta * cfg.transaction_cost_stk * stock_ivols)

         return tc_idx + tc_stk

    def run_backtest(self,
                     data: pd.DataFrame,
                     notional: float = 10_000_000,
                     rebal_freq: int = 21) -> pd.DataFrame:
        results = []
        T = len(data)
        for t in range(0, T, rebal_freq):
            if t + rebal_freq > T:
                break

            row = data.iloc[t]
            period_end = min(t + rebal_freq, T)
            period_data = data.iloc[t:period_end]

            avg_impl_corr = row.get('impl_corr', 0.45)
            avg_real_corr = period_data['real_corr'].mean()

            sig_wb = row.get('sigma_w_bar', 0.28)
            var_avg = row.get('var_avg', 0.06)

            period_pnl = notional * (avg_impl_corr - avg_real_corr) * (sig_wb ** 2 - var_avg)

            results.append({
                'date': data.index[t],
                'period_pnl': period_pnl,
                'impl_corr': avg_impl_corr,
                'real_corr': avg_real_corr,
                'crp': avg_impl_corr - avg_real_corr,
            })

        df = pd.DataFrame(results).set_index('date')
        df['cum_pnl'] = df['period_pnl'].cumsum()
        return df


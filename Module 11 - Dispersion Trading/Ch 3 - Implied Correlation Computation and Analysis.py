import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.dates as mdates
from scipy.stats import pearsonr

class ImpliedCorrelationAnalyzer:
    """
    Computes and analyzes implied correlation from index and
    single-stock implied volatility data.
    """
    def __init__(self, weights: np.ndarray, names: list = None):
        """
        Parameters
        ----------
        weights : array, shape (N,) -- constituent weights
        names : list of str -- constituent names
        """
        self.weights = np.array(weights)
        self.weights /= self.weights.sum() # Normalize
        self.N = len(weights)
        self.names = names or [f'Stock_{i}' for i in range(self.N)]

    def implied_correlation(self, idx_ivol: float, stock_ivols: np.ndarray) -> float:
        w = self.weights
        v = np.array(stock_ivols)

        numerator = idx_ivol**2 - np.sum((w * v)**2)
        denominator = np.sum(w * v)**2 - np.sum((w * v)**2)

        if abs(denominator) < 1e-12:
            return np.nan

        rho_impl = numerator / denominator
        return rho_impl

    def implied_corr_timeseries(self, idx_ivol_series: pd.Series, stock_ivol_df: pd.DataFrame) -> pd.Series:
        """
        Compute time series of implied correlation.
        """
        results = {}
        common_idx = idx_ivol_series.index.intersection(stock_ivol_df.index)

        for date in common_idx:
            sig_I = idx_ivol_series.loc[date]
            sigs = stock_ivol_df.loc[date].values
            if np.any(np.isnan(sigs)) or np.isnan(sig_I):
                results[date] = np.nan
            else:
                results[date] = self.implied_correlation(sig_I, sigs)

        return pd.Series(results, name='ImpliedCorr')

    def correlation_risk_premium(self, impl_corr: pd.Series, real_corr: pd.Series, lag: int = 21) -> pd.Series:
        real_fwd = real_corr.shift(-lag)
        crp = impl_corr - real_fwd
        crp.name = 'CRP'
        return crp

    def vix_corr_regime(self, vix_series: pd.Series, impl_corr: pd.Series) -> pd.DataFrame:
        """ Analyze implied correlation by VIX regime ."""
        df = pd.concat([vix_series.rename('VIX'), impl_corr], axis=1).dropna()

        bins = [0, 15, 20, 25, 35, 100]
        labels = ['<15', '15-20', '20-25', '25-35', '>35']
        df['VIX_regime'] = pd.cut(df['VIX'], bins=bins, labels=labels)

        summary = df.groupby('VIX_regime')['ImpliedCorr'].agg(
            ['mean', 'median', 'std', 'count']
        ).round(4)
        return summary


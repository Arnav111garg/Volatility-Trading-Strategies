import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import expon

def heston_jump_vol(kappa, theta, xi, rho, v0, S0, r, T, lam=0.5, mu_v=0.10, mu_S=-0.08, sig_S=0.05, N=5000, M=252):
    """
    Heston model with jump in both S and v (Bates model extension).
    """
    dt = T / M
    sqrt_dt = np.sqrt(dt)
    S = np.full(N, float(S0))
    v = np.full(N, float(v0))
    all_v = np.zeros((N, M))
    all_S = np.zeros((N, M))

    for m in range(M):
        z1 = np.random.randn(N)
        z2 = rho * z1 + np.sqrt(1 - rho**2) * np.random.randn(N)
        v_pos = np.maximum(v, 1e-10)

        # Diffusion
        v += kappa * (theta - v_pos) * dt + xi * np.sqrt(v_pos) * sqrt_dt * z2
        v = np.maximum(v, 0)
        S *= np.exp((r - 0.5 * v_pos) * dt + np.sqrt(v_pos * dt) * z1)

        # Jumps (Poisson)
        n_jumps = np.random.poisson(lam * dt, N)
        has_jump = n_jumps > 0
        if has_jump.any():
            jv = expon.rvs(scale=mu_v, size=has_jump.sum())
            js = mu_S + sig_S * np.random.randn(has_jump.sum())
            v[has_jump] += jv
            S[has_jump] *= np.exp(js)

        all_v[:, m] = v
        all_S[:, m] = S

    return all_S, all_v

np.random.seed(12)

# Normal market
S_n, v_n = heston_jump_vol(kappa=3, theta=0.04, xi=0.3, rho=-0.6, v0=0.04, S0=100, r=0, T=1, lam=0.2, mu_v=0.03, N=3000)

# Crisis scenario
S_c, v_c = heston_jump_vol(kappa=2, theta=0.12, xi=0.6, rho=-0.85, v0=0.08, S0=100, r=0, T=1, lam=1.5, mu_v=0.08, N=3000)

t = np.linspace(0, 1, 252)

fig, axes = plt.subplots(2, 2, figsize=(9, 7))

# Normal vol paths
idx = np.random.choice(3000, 30)
for i in idx:
    axes[0, 0].plot(t, np.sqrt(v_n[i] * 252) * 100, lw=0.6, alpha=0.5, color='blue')
axes[0, 0].plot(t, np.sqrt(v_n.mean(0) * 252) * 100, lw=2, color='darkblue', label='Mean')
axes[0, 0].set_title('Volatility Paths Normal Regime')
axes[0, 0].set_ylabel('Ann. Vol %')
axes[0, 0].legend()

# Crisis vol paths
for i in idx:
    axes[0, 1].plot(t, np.sqrt(v_c[i] * 252) * 100, lw=0.6, alpha=0.5, color='red')
axes[0, 1].plot(t, np.sqrt(v_c.mean(0) * 252) * 100, lw=2, color='darkred', label='Mean')
axes[0, 1].set_title('Volatility Paths Crisis Regime')
axes[0, 1].set_ylabel('Ann. Vol %')
axes[0, 1].legend()

# Return distributions
ret_n = np.log(S_n[:, -1] / 100)
ret_c = np.log(S_c[:, -1] / 100)
for data, color, label in [(ret_n, 'blue', 'Normal'), (ret_c, 'red', 'Crisis')]:
    axes[1, 0].hist(data, bins=100, density=True, alpha=0.5, color=color, label=label)
axes[1, 0].set_xlabel('Log Return')
axes[1, 0].set_title('1Y Return Distribution')
axes[1, 0].legend()

# VoV realization
vov_n = np.std(np.diff(np.sqrt(v_n * 252) * 100, axis=1), axis=1)
vov_c = np.std(np.diff(np.sqrt(v_c * 252) * 100, axis=1), axis=1)
axes[1, 1].hist(vov_n, bins=80, density=True, alpha=0.6, color='blue', label='Normal')
axes[1, 1].hist(vov_c, bins=80, density=True, alpha=0.6, color='red', label='Crisis')
axes[1, 1].set_xlabel('Realized Vol-of-Vol')
axes[1, 1].set_title('VoV Distribution')
axes[1, 1].legend()

plt.tight_layout()
plt.savefig('crisis_dynamics.pdf', dpi=150)
plt.show()


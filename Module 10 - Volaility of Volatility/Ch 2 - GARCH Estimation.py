import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from arch import arch_model
from scipy.stats import probplot, norm

# Download data
spx = yf.download('^GSPC', start='2010-01-01', end='2024-01-01', auto_adjust=True)

# Access 'Close' under the MultiIndex structure
close_prices = spx['Close']['^GSPC']
ret = 100 * np.log(close_prices / close_prices.shift(1)).dropna()

# --- GARCH (1,1) ---
am = arch_model(ret, vol='Garch', p=1, q=1, dist='Normal')
res = am.fit(disp='off')
print(res.summary())

# Extract parameters
omega, alpha, beta = res.params['omega'], res.params['alpha[1]'], res.params['beta[1]']
persistence = alpha + beta
long_run_sigma = np.sqrt(omega / (1 - persistence)) * np.sqrt(252)
half_life = np.log(0.5) / np.log(persistence)

print(f"Persistence (alpha + beta): {persistence:.4f}")
print(f"Long-run annual vol: {long_run_sigma:.2f}%")
print(f"Vol half-life (days): {half_life:.1f}")

# --- Conditional volatility ---
cond_vol = res.conditional_volatility * np.sqrt(252)
sigma_series = res.conditional_volatility
vov_approx = (sigma_series.diff().std() / sigma_series.mean()) * np.sqrt(252)
print(f"Approximate annualized GARCH Vol-of-Vol: {vov_approx:.3f}")

# --- Compare GARCH (1,1) vs GJR-GARCH (asymmetric) ---
gjr = arch_model(ret, vol='Garch', p=1, o=1, q=1, dist='Normal')
gjr_res = gjr.fit(disp='off')
print(f"\nGJR-GARCH news impact asymmetry (gamma): {gjr_res.params['gamma[1]']:.4f}")

# --- Plot ---
fig, axes = plt.subplots(2, 1, figsize=(14, 8), sharex=True)
axes[0].plot(ret.index, ret, lw=0.5, color='gray', alpha=0.8, label='Returns')
axes[0].fill_between(ret.index, -2 * cond_vol, 2 * cond_vol, alpha=0.3, color='blue', label=r'$\pm 2\sigma$ band')
axes[0].legend()
axes[0].set_title('GARCH (1,1) Conditional Volatility Bands')

axes[1].plot(cond_vol.index, cond_vol, color='darkblue', lw=1.2, label='GARCH')
axes[1].set_ylabel('Ann. Cond. Vol (%)')
axes[1].legend()
plt.tight_layout()
plt.savefig('garch_vol.pdf', dpi=150)
plt.show()


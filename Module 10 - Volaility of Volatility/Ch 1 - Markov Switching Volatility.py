import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from statsmodels.tsa.regime_switching.markov_regression import MarkovRegression

# Download SPX data
spx = yf.download('^GSPC', start='2005-01-01', end='2024-01-01')

# Access 'Close' under the MultiIndex structure
close_prices = spx['Close']['^GSPC']
ret = 100 * np.log(close_prices / close_prices.shift(1)).dropna()

# Fit 3-state Markov-switching model (switching variance and trend)
mod = MarkovRegression(ret, k_regimes=3, switching_variance=True, switching_trend=True)
res = mod.fit(search_reps=10, search_iter=100)
print(res.summary())

# Extract smoothed probabilities
smoothed_probs = res.smoothed_marginal_probabilities

# Plot regimes
fig, axes = plt.subplots(3, 1, figsize=(14, 10), sharex=True)

axes[0].plot(ret.index, ret, color='gray', linewidth=0.5, alpha=0.8)
axes[0].set_ylabel('SPX Returns (%)')
axes[0].set_title('SPX Returns and Volatility Regimes')

# Shade regimes
colors = ['#c8e6c9', '#fff9c4', '#ffcdd2'] # green, yellow, red
labels = ['Low Vol', 'Medium Vol', 'High Vol / Crisis']
for k, (color, label) in enumerate(zip(colors, labels)):
    axes[1].fill_between(smoothed_probs.index,
                             smoothed_probs.iloc[:, k],
                             alpha=0.7, color=color, label=label)
axes[1].legend(loc='upper right', fontsize=8)
axes[1].set_ylabel('Regime Probability')

# Inferred regime volatilities
regime_vols = np.sqrt(res.params[res.model.parameters['variance']] * 252)
print(f"Regime volatilities (annualized): {regime_vols}")

# Plot smoothed variance
smoothed_var = sum(p * s**2 for p, s in
                   zip([smoothed_probs.iloc[:, k] for k in range(3)],
                       res.params[res.model.parameters['variance']]))
axes[2].plot(smoothed_probs.index, np.sqrt(smoothed_var * 252),
             color='darkblue', linewidth=1)
axes[2].set_ylabel('Smoothed Ann. Vol (%)')
axes[2].set_xlabel('Date')

plt.tight_layout()
plt.savefig('hmm_regimes.pdf', dpi=150)
plt.show()


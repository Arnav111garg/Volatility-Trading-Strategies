import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import norm
from mpl_toolkits.mplot3d import Axes3D

def black_scholes(S, K, T, r, sigma, option='call'):
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    if option == 'call':
        return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    else:
        return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)

def vega(S, K, T, r, sigma):
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    return S * norm.pdf(d1) * np.sqrt(T)

def vomma(S, K, T, r, sigma):
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    return vega(S, K, T, r, sigma) * d1 * d2 / sigma

# Grid
S = 100.0
r = 0.0
sigma = 0.20
strikes = np.linspace(70, 130, 60)
maturities = np.linspace(0.05, 2.0, 60)
K_grid, T_grid = np.meshgrid(strikes, maturities)

# Vomma surface
vomma_surface = vomma(S, K_grid, T_grid, r, sigma)

# Plot
fig = plt.figure(figsize=(14, 6))

ax1 = fig.add_subplot(121, projection='3d')
surf = ax1.plot_surface(K_grid, T_grid, vomma_surface, cmap='RdBu_r', alpha=0.9, linewidth=0)
ax1.set_xlabel('Strike K')
ax1.set_ylabel('Maturity T (yrs)')
ax1.set_zlabel('Vomma')
ax1.set_title(f'Vomma Surface (S={S}, vol={sigma})')
plt.colorbar(surf, ax=ax1, shrink=0.5)

# Vomma slice at T = 0.25
ax2 = fig.add_subplot(122)
T_slice = 0.25
vomma_slice = vomma(S, strikes, T_slice, r, sigma)
ax2.plot(strikes, vomma_slice, color='darkblue', lw=2, label=f'T = {T_slice} yr')
ax2.fill_between(strikes, vomma_slice, alpha=0.3, where=(vomma_slice > 0), color='green', label='Vomma > 0')
ax2.fill_between(strikes, vomma_slice, alpha=0.3, where=(vomma_slice < 0), color='red', label='Vomma < 0')

ax2.axvline(S, color='gray', linestyle='--', lw=1, label='ATM')
ax2.axhline(0, color='black', lw=0.8)
ax2.set_xlabel('Strike K')
ax2.set_ylabel('Vomma')
ax2.set_title('Vomma by Strike (T = 0.25 yr, ATM Vol = 20%)')
ax2.legend()
plt.tight_layout()
plt.savefig('vomma_surface.pdf', dpi=150)
plt.show()


import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import norm

def heston_mc(kappa, theta, xi, rho, v0, S0, r, T, N=1000, M=252):
    """
    Heston Monte Carlo simulation.
    Returns (S_T array, realized_var array)
    """
    dt = T / M
    S = np.full(N, S0, dtype=float)
    v = np.full(N, v0, dtype=float)
    rv_sum = np.zeros(N)

    for _ in range(M):
        z1 = np.random.standard_normal(N)
        z2 = rho * z1 + np.sqrt(1 - rho**2) * np.random.standard_normal(N)
        v_pos = np.maximum(v, 0)
        dv = kappa * (theta - v_pos) * dt + xi * np.sqrt(v_pos * dt) * z2
        dS = r * S * dt + np.sqrt(v_pos * dt) * S * z1
        S += dS
        v += dv
        v = np.maximum(v, 0)
        rv_sum += v_pos * dt

    realized_var = rv_sum / T
    return S, realized_var

# Parameters
kappa = 3.0
theta = 0.04
xi = 0.4
rho = -0.7
v0 = 0.04
S0 = 100
r = 0.0
T = 1.0

np.random.seed(42)
S_T, rv = heston_mc(kappa, theta, xi, rho, v0, S0, r, T, N=10000)

# Fair variance swap strike (approximately theta for long T)
K_var = theta  # simplification for illustration

# Short variance swap P&L
pnl_short_var = K_var - rv

print("=== Short Variance Swap Statistics ===")
print(f"Strike K_var (annualized): {np.sqrt(K_var) * 100:.2f}% vol")
print(f"Mean RV: {np.sqrt(rv.mean()) * 100:.2f}% vol")
print(f"Mean P&L: {pnl_short_var.mean():.6f} (var units)")
print(f"P&L Std: {pnl_short_var.std():.6f}")
print(f"P&L Skew: {((pnl_short_var - pnl_short_var.mean())**3).mean() / pnl_short_var.std()**3:.3f}")
print(f"P&L Kurtosis: {((pnl_short_var - pnl_short_var.mean())**4).mean() / pnl_short_var.std()**4:.3f}")
print(f"P(P&L > 0): {(pnl_short_var > 0).mean():.3f}")
print(f"Mean loss | loss: {pnl_short_var[pnl_short_var < 0].mean():.6f}")
print(f"Worst 5% loss: {np.percentile(pnl_short_var, 5):.6f}")
print(f"Worst 1% loss: {np.percentile(pnl_short_var, 1):.6f}")

# Plot
fig, axes = plt.subplots(1, 2, figsize=(14, 5))
axes[0].hist(np.sqrt(rv) * 100, bins=80, color='steelblue', edgecolor='white', alpha=0.7, density=True)
axes[0].axvline(np.sqrt(K_var) * 100, color='red', lw=2, label='Strike')
axes[0].axvline(np.sqrt(rv.mean()) * 100, color='green', lw=2, linestyle='--', label='Mean RV')
axes[0].set_xlabel('Realized Vol (%)')
axes[0].set_title('RV Distribution')
axes[0].legend()

axes[1].hist(pnl_short_var, bins=80, color='darkorange', edgecolor='white', alpha=0.7, density=True)
axes[1].axvline(0, color='black', lw=1)
axes[1].axvline(np.percentile(pnl_short_var, 5), color='red', lw=1.5, linestyle='--', label='5th pctile')
axes[1].set_xlabel('P&L (var units)')
axes[1].set_title('Short Var Swap P&L')
axes[1].legend()

plt.tight_layout()
plt.savefig('short_var_pnl.pdf', dpi=150)
plt.show()


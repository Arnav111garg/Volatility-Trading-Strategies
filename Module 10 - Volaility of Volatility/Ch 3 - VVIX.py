import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from scipy import stats

# Download VIX, VVIX and SPX
vix_df = yf.download('^VIX', start='2010-01-01', end='2024-01-01')
vvix_df = yf.download('^VVIX', start='2010-01-01', end='2024-01-01')
spx_df = yf.download('^GSPC', start='2010-01-01', end='2024-01-01')

# Extract Close prices handling MultiIndex if present
vix = vix_df['Close']['^VIX'] if isinstance(vix_df.columns, pd.MultiIndex) else vix_df['Close']
vvix = vvix_df['Close']['^VVIX'] if isinstance(vvix_df.columns, pd.MultiIndex) else vvix_df['Close']
spx = spx_df['Close']['^GSPC'] if isinstance(spx_df.columns, pd.MultiIndex) else spx_df['Close']

df = pd.DataFrame({'VIX': vix, 'VVIX': vvix, 'SPX': spx}).dropna()

# VVIX /VIX Ratio
df['ratio'] = df['VVIX'] / df['VIX']
df['spx_fwd_ret'] = df['SPX'].pct_change(21).shift(-21)  # 1-month forward

# --- Predictive regression : does VVIX ratio predict returns ? ---
ratio_q90 = df['ratio'].quantile(0.90)
high_ratio = df[df['ratio'] > ratio_q90]
low_ratio = df[df['ratio'] <= ratio_q90]

print("=== Predictive Power of VVIX/VIX Ratio ===")
print(f"90th percentile of ratio: {ratio_q90:.2f}")
print(f"Mean fwd return when ratio HIGH: {high_ratio['spx_fwd_ret'].mean() * 100:.2f}%")
print(f"Mean fwd return when ratio LOW: {low_ratio['spx_fwd_ret'].mean() * 100:.2f}%")
t_stat, p_val = stats.ttest_ind(high_ratio['spx_fwd_ret'].dropna(), low_ratio['spx_fwd_ret'].dropna())
print(f"t-stat: {t_stat:.2f}, p-value: {p_val:.4f}")

# --- VVIX Implied Vol-of-Vol ---
# VVIX is already the implied vol of VIX in %
# Convert to daily VIX move expected (1-sigma)
df['expected_vix_daily_move'] = df['VVIX'] / 100 * df['VIX'] / np.sqrt(252)
print(f"\nMean expected daily VIX move (1-sigma): {df['expected_vix_daily_move'].mean():.2f} vol points")

# --- Visualization ---
fig, axes = plt.subplots(3, 1, figsize=(14, 12), sharex=True)

axes[0].plot(df.index, df['VIX'], color='darkblue', lw=1.2, label='VIX')
axes[0].plot(df.index, df['VVIX'], color='darkred', lw=1.0, alpha=0.8, label='VVIX', linestyle='--')
axes[0].legend()
axes[0].set_ylabel('Level')
axes[0].set_title('VIX vs VVIX')

axes[1].plot(df.index, df['ratio'], color='purple', lw=1.2, label='VVIX/VIX')
axes[1].axhline(ratio_q90, color='red', linestyle='--', lw=0.8, label=f'90th pctile = {ratio_q90:.1f}')
axes[1].axhline(df['ratio'].mean(), color='gray', linestyle=':', lw=0.8, label='Mean')
axes[1].legend()
axes[1].set_ylabel('VVIX/VIX Ratio')

axes[2].plot(df.index, df['expected_vix_daily_move'], color='darkorange', lw=1.2)
axes[2].set_ylabel('Expected VIX Daily Move (vol pts)')
axes[2].set_xlabel('Date')

plt.tight_layout()
plt.savefig('vvix_analysis.pdf', dpi=150)
plt.show()


import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import odeint

# Parameters
kappa = 3.0           # base mean-reversion
theta_ss = 0.04       # steady-state variance
xi = 0.4              # diffusion vol-of-vol
alpha_gamma = 2.5     # gamma cascade intensity
alpha_rho = 0.8       # correlation cascade intensity
v_star = 0.06         # gamma-flip level
rho0 = -0.5           # normal return-vol correlation
rho_max = -0.95       # crisis correlation
v_half = 0.08         # half-saturation for correlation cascade

def rho_of_v(v):
    """ Sigmoid correlation model """
    return rho0 + (rho_max - rho0) * v / (v + v_half)

def cascade_system(state, t, shock_start=0.5, shock_end=0.6, shock_mag=0.08):
    """ Deterministic cascade system with exogenous shock """
    v, theta = state

    # Exogenous shock to theta
    if shock_start <= t <= shock_end:
        theta_shock = shock_mag
    else:
        theta_shock = 0

    # Gamma cascade term (activates above v_star)
    gamma_cascade = (alpha_gamma * (v - theta) * np.maximum(v - v_star, 0)) / (v + 0.01)

    # Correlation cascade
    rho_t = rho_of_v(v)
    corr_cascade = alpha_rho * abs(rho_t - rho0) * v

    # Dynamics
    dv = -kappa * (v - theta - theta_shock) + gamma_cascade + corr_cascade
    dtheta = 0.1 * (theta_ss - theta) + 0.5 * theta_shock  # theta adjusts slowly

    return [dv, dtheta]

t = np.linspace(0, 3, 3000)

fig, axes = plt.subplots(3, 1, figsize=(14, 12), sharex=True)

colors = ['darkblue', 'darkred']
labels = ['Base (no cascade)', 'Cascade (alpha_gamma=2.5)']
alphas_gamma = [0.0, 2.5]

for idx, ag in enumerate(alphas_gamma):
    # Temporarily set the cascade intensity
    current_alpha_gamma = ag

    # Redefine the cascade system inline or dynamically with correct global-like scoping
    def system(state, t_step):
        v, theta = state
        if 0.5 <= t_step <= 0.6:
            theta_shock = 0.08
        else:
            theta_shock = 0
        gamma_cascade = (current_alpha_gamma * (v - theta) * np.maximum(v - v_star, 0)) / (v + 0.01)
        rho_t = rho_of_v(v)
        corr_cascade = alpha_rho * abs(rho_t - rho0) * v
        dv = -kappa * (v - theta - theta_shock) + gamma_cascade + corr_cascade
        dtheta = 0.1 * (theta_ss - theta) + 0.5 * theta_shock
        return [dv, dtheta]

    sol = odeint(system, [0.04, 0.04], t)
    v_t = sol[:, 0]
    theta_t = sol[:, 1]

    axes[0].plot(t, np.sqrt(np.maximum(v_t, 0) * 252) * 100, color=colors[idx], lw=1.8, label=labels[idx])
    axes[1].plot(t, rho_of_v(v_t), color=colors[idx], lw=1.8, linestyle=['--', '-'][idx])

    # Vol-of-vol: rolling std of v changes
    dv = np.diff(v_t)
    vov = np.array([np.std(dv[max(0, i-20):i+1]) for i in range(len(dv))])
    axes[2].plot(t[1:], vov * 100, color=colors[idx], lw=1.5)

axes[0].axvspan(0.5, 0.6, alpha=0.14998244353, color='red', label='Shock period')
axes[0].set_ylabel('Ann. Vol (%)')
axes[0].set_title('Volatility Cascade Dynamics: Effect of Gamma Cascade')
axes[0].legend()

axes[1].axhline(rho0, color='gray', linestyle=':', lw=0.8)
axes[1].set_ylabel('Corr(S, v)')
axes[1].set_title('Return - Volatility Correlation During Cascade')

axes[2].set_ylabel('Realized VoV (scaled)')
axes[2].set_xlabel('Time (years)')
axes[2].set_title('Vol-of-Vol During Cascade')

plt.tight_layout()
plt.savefig('cascade_simulation.pdf', dpi=150)
plt.show()


import numpy as np
import pandas as pd
from scipy.stats import norm

class OptionsLiquidityAnalytics:
    """
    Comprehensive options market liquidity measurement system.
    Computes spreads, Amihud ILLIQ, liquidity cycles, and pin risk.
    """
    def __init__(self):
        pass

    def volume_weighted_effective_spread(self, trades: pd.DataFrame) -> float:
        """
        Compute VWES from trade-and-quote (TAQ) data.

        trades columns: trade_price, bid, ask, quantity
        """
        mid = (trades['bid'] + trades['ask']) / 2.0
        eff_spread = 2.0 * abs(trades['trade_price'] - mid)
        vwes = np.average(eff_spread, weights=trades['quantity'])
        return vwes

    def amihud_illiquidity(self, daily_data: pd.DataFrame) -> pd.Series:
        """
        Compute Amihud (2002) illiquidity for options.

        daily_data columns: date, option_id, price_change_pct, dollar_volume
        """
        daily_data = daily_data.copy()
        daily_data['illiq_daily'] = abs(daily_data['price_change_pct']) / (daily_data['dollar_volume'] + 1e-10)
        return daily_data.groupby('option_id')['illiq_daily'].mean().rename('amihud_illiq')

    def spread_decomposition(
        self,
        S: float,
        K: float,
        T: float,
        r: float,
        sigma: float,
        observed_spread: float,
        q: int = 1,
        adv: float = 1e6
    ) -> dict:
        """
        Decompose observed bid-ask spread into components.

        Returns dict with:
        fixed_cost, inventory_cost, gamma_cost, adverse_selection, total_model, residual
        """
        T_adj = max(T, 1e-10)
        d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T_adj) / (sigma * np.sqrt(T_adj))
        d2 = d1 - sigma * np.sqrt(T_adj)
        gamma = norm.pdf(d1) / (S * sigma * np.sqrt(T_adj))
        delta = abs(norm.cdf(d1))

        # Component estimates (calibrated to SPX market data)
        c0 = 0.05  # Fixed cost
        c1 = 0.002 * q  # Size cost
        inv_cost = 0.003 * delta  # Delta inventory
        gamma_cost = 0.01 * gamma * S ** 2  # Gamma cost

        # Adverse selection: Kyle lambda proxy
        lambda_kyle = sigma * np.sqrt(np.pi / (2 * adv)) * S
        adverse_sel = lambda_kyle * q * delta

        total_model = 2.0 * (c0 + c1 + inv_cost + gamma_cost + adverse_sel)

        return {
            'fixed_cost': 2 * c0,
            'size_cost': 2 * c1,
            'inventory_cost': 2 * inv_cost,
            'gamma_cost': 2 * gamma_cost,
            'adverse_selection': 2 * adverse_sel,
            'total_model': total_model,
            'observed_spread': observed_spread,
            'residual': observed_spread - total_model,
            'model_fit_pct': total_model / (observed_spread + 1e-10) * 100
        }

    def pin_risk_score(
        self,
        S: float,
        strikes: np.ndarray,
        oi_by_strike: np.ndarray,
        T: float
    ) -> dict:
        """
        Compute pin risk score: how likely is the market to pin at a strike?

        Returns the strike with highest pin risk and the score.
        Pin risk ~ OI * gamma near expiry (charm effect)
        """
        sigma_atm = 0.18
        T_adj = max(T, 1.0 / 365 / 24)  # at least 1 hour
        gammas = norm.pdf((np.log(S / strikes) + 0.5 * sigma_atm ** 2 * T_adj) / (sigma_atm * np.sqrt(T_adj))) / (S * sigma_atm * np.sqrt(T_adj))

        # Pin score: OI * gamma (normalised)
        pin_scores = oi_by_strike * gammas
        pin_scores /= pin_scores.max() + 1e-10

        highest_pin_strike = strikes[np.argmax(pin_scores)]

        return {
            'pin_strikes': strikes,
            'pin_scores': pin_scores,
            'highest_pin_strike': highest_pin_strike,
            'distance_pct': (highest_pin_strike - S) / S * 100,
            'pin_risk': 'HIGH' if pin_scores.max() > 0.7 else 'MODERATE'
        }

    def liquidity_regime_detector(
        self,
        spread_ts: pd.Series,
        vol_ts: pd.Series,
        window: int = 20
    ) -> pd.DataFrame:
        """
        Detect liquidity regimes using spread-vol decomposition.

        Returns DataFrame with regime classifications.
        """
        df = pd.DataFrame({'spread': spread_ts, 'vol': vol_ts})
        df['spread_z'] = (df['spread'] - df['spread'].rolling(window).mean()) / df['spread'].rolling(window).std()
        df['vol_z'] = (df['vol'] - df['vol'].rolling(window).mean()) / df['vol'].rolling(window).std()

        conditions = [
            (df['spread_z'] > 1.5) & (df['vol_z'] > 1.5),
            (df['spread_z'] > 1.0) & (df['vol_z'] > 1.0),
            (df['spread_z'] < -0.5) & (df['vol_z'] < -0.5)
        ]
        choices = ['CRISIS (Liquidity Spiral)', 'STRESSED', 'BENIGN']
        df['regime'] = np.select(conditions, choices, default='NORMAL')

        return df


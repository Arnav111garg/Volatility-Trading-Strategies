import numpy as np
import pandas as pd
from scipy.stats import norm
from dataclasses import dataclass
from typing import Dict, List, Tuple

@dataclass
class OptionContract:
    strike: float
    expiry_T: float  # years
    option_type: str  # 'call' or 'put'
    oi: int  # open interest (contracts)
    iv: float  # implied vol
    dealer_sign: int  # +1 = dealer long, -1 = dealer short

class DealerPositioningDashboard:
    def __init__(self, S: float, r: float = 0.05, m: int = 100):
        self.S = S
        self.r = r
        self.m = m

    def compute_all_greeks(self, K: float, T: float, r: float, sigma: float) -> dict:
        """Return all relevant greeks as a dict."""
        T = max(T, 1e-10)
        sqrt_T = np.sqrt(T)
        d1 = (np.log(self.S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * sqrt_T)
        d2 = d1 - sigma * sqrt_T
        phi_d1 = norm.pdf(d1)

        return {
            'delta_call': norm.cdf(d1),
            'delta_put': norm.cdf(d1) - 1.0,
            'gamma': phi_d1 / (self.S * sigma * sqrt_T),
            'vega': self.S * sqrt_T * phi_d1 / 100.0,
            'theta_call': (-(self.S * phi_d1 * sigma / (2 * sqrt_T)) - r * K * np.exp(-r * T) * norm.cdf(d2)) / 365,
            'theta_put': (-(self.S * phi_d1 * sigma / (2 * sqrt_T)) + r * K * np.exp(-r * T) * norm.cdf(-d2)) / 365,
            'vanna': -phi_d1 * d2 / sigma,
            'charm_call': -phi_d1 * (r / (sigma * sqrt_T) - d2 / (2 * T)),
            'charm_put': -phi_d1 * (r / (sigma * sqrt_T) - d2 / (2 * T)),
            'volga': self.S * sqrt_T * phi_d1 * d1 * d2 / sigma / 100.0,
            'd1': d1,
            'd2': d2
        }

    def full_book_analysis(self, contracts: List[OptionContract]) -> Dict:
        """
        Complete dealer book analysis.
        Returns all exposures and key positioning levels.
        """
        rows = []
        for c in contracts:
            g = self.compute_all_greeks(c.strike, c.expiry_T, self.r, c.iv)

            delta = g['delta_call'] if c.option_type == 'call' else g['delta_put']
            charm = g['charm_call'] if c.option_type == 'call' else g['charm_put']
            theta = g['theta_call'] if c.option_type == 'call' else g['theta_put']

            net_qty = c.oi * c.dealer_sign * self.m

            rows.append({
                'strike': c.strike,
                'expiry_T': c.expiry_T,
                'type': c.option_type,
                'oi': c.oi,
                'dealer_sign': c.dealer_sign,
                # Raw Greeks
                'delta': delta,
                'gamma': g['gamma'],
                'vega': g['vega'],
                'vanna': g['vanna'],
                'charm': charm,
                'volga': g['volga'],
                # Book exposures ($ notional)
                'DEX': net_qty * delta * self.S,
                'GEX': net_qty * g['gamma'] * self.S ** 2 * (1 if c.option_type == 'call' else -1),
                'VEX': net_qty * g['vega'],
                'VAEX': net_qty * g['vanna'] * self.S,
                'CHEX': net_qty * charm * self.S,
                'VEGEX': net_qty * g['volga'],
                'TEX': net_qty * theta,
            })

        df = pd.DataFrame(rows)

        # Key levels
        gex_by_strike = df.groupby('strike')['GEX'].sum()
        put_wall = gex_by_strike[gex_by_strike < 0].abs().idxmax() if (gex_by_strike < 0).any() else None
        call_wall = gex_by_strike[gex_by_strike > 0].idxmax() if (gex_by_strike > 0).any() else None

        # ZGL: find where cumulative GEX crosses zero
        profile = self._compute_gex_profile(df, np.linspace(self.S * 0.9, self.S * 1.1, 100))
        sign_changes = np.where(np.diff(np.sign(profile['GEX'].values)))[0]
        zgl = profile['spot'].iloc[sign_changes[0]] if len(sign_changes) > 0 else None

        return {
            'DEX': df['DEX'].sum(),
            'GEX': df['GEX'].sum(),
            'VEX': df['VEX'].sum(),
            'VAEX': df['VAEX'].sum(),
            'CHEX': df['CHEX'].sum(),
            'VEGEX': df['VEGEX'].sum(),
            'TEX': df['TEX'].sum(),
            'put_wall': put_wall,
            'call_wall': call_wall,
            'zero_gamma_level': zgl,
            'gex_by_strike': gex_by_strike,
            'detail': df,
            'gex_profile': profile
        }

    def _compute_gex_profile(self, df: pd.DataFrame, spot_range: np.ndarray) -> pd.DataFrame:
        records = []
        for s in spot_range:
            gex_s = 0
            for _, row in df.iterrows():
                g = self.compute_all_greeks(row['strike'], row['expiry_T'], self.r, row.get('iv', 0.18))
                sign = 1 if row['type'] == 'call' else -1
                gex_s += row['dealer_sign'] * row['oi'] * self.m * g['gamma'] * s ** 2 * sign
            records.append({'spot': s, 'GEX': gex_s})
        return pd.DataFrame(records)

    def opex_charm_flow(self, df: pd.DataFrame, days_to_opex: int = 3) -> dict:
        """
        Estimate charm-driven rebalancing flow into OPEX.
        Returns expected directional flow from charm hedging.
        """
        T_opex = days_to_opex / 365.0
        # Filter to near-expiry options
        near = df[df['expiry_T'] <= T_opex + 5 / 365]
        total_charm_flow = near['CHEX'].sum()

        return {
            'charm_rebalancing': total_charm_flow,
            'direction': 'BUY' if total_charm_flow > 0 else 'SELL',
            'magnitude_shares': abs(total_charm_flow) / self.S,
            'days_to_opex': days_to_opex
        }


# Core Impact Models
#

class OptionsMarketImpact:
    """
    Unified options market impact modelling framework.

    Implements:
    - Square-root law (vol impact)
    - Kyle lambda estimation (vol domain)
    - Almgren-Chriss optimal execution
    - Options-to-equity propagation
    - Intraday impact scheduling
    """
    def __init__(
        self,
        S: float,
        sigma_atm: float,
        adv_vega: float = 5e8,
        adv_equity: float = 2e10,
        eta: float = 0.20,
        r: float = 0.05,
        m: int = 100
    ):
        self.S = S
        self.sigma_atm = sigma_atm
        self.adv_vega = adv_vega        # avg daily vega-notional
        self.adv_equity = adv_equity    # avg daily equity notional
        self.eta = eta                  # sqrt-law coefficient
        self.r = r
        self.m = m

    # 1. Square-Root Vol Impact
    def sqrt_vol_impact(
        self,
        q_contracts: float,
        K: float,
        T: float,
        iv: float,
        side: int = 1
    ) -> dict:
        # Vega of the option
        d1 = (np.log(self.S / K) + (self.r + 0.5 * iv ** 2) * T) / (iv * np.sqrt(T))
        vega_per_contract = self.S * np.sqrt(T) * norm.pdf(d1) * self.m / 100.0

        # Vega-notional of the order
        q_vega = abs(q_contracts) * vega_per_contract

        # Square-root impact (in vol points)
        delta_sigma = self.eta * self.sigma_atm * np.sqrt(q_vega / (self.adv_vega + 1e-10))
        delta_sigma *= side  # Buying increases vol, selling decreases

        # Dollar impact
        dollar_impact = delta_sigma * 100 * q_vega  # per 1% move times vega

        return {
            'vega_per_contract': vega_per_contract,
            'q_vega_notional': q_vega,
            'delta_sigma_pts': delta_sigma * 100,  # in percentage points
            'dollar_impact': dollar_impact,
            'participation_pct': q_vega / self.adv_vega * 100,
            'impact_regime': ('HIGH' if q_vega / self.adv_vega > 0.05 else 'MODERATE' if q_vega / self.adv_vega > 0.01 else 'LOW')
        }

    # 2. Kyle Lambda Estimation
    def kyle_lambda_vol(
        self,
        flow_series: pd.Series,
        iv_series: pd.Series,
        window: int = 60
    ) -> pd.Series:
        delta_iv = iv_series.diff().fillna(0)
        lambdas = []
        for i in range(window, len(flow_series)):
            f = flow_series.iloc[i - window : i].values
            v = delta_iv.iloc[i - window : i].values
            cov = np.cov(f, v, ddof=1)
            if cov[0, 0] > 0:
                lam = cov[0, 1] / cov[0, 0]
            else:
                lam = np.nan
            lambdas.append(lam)

        return pd.Series(
            lambdas,
            index=flow_series.index[window:],
            name='kyle_lambda_vol'
        )

    # 3. Almgren-Chriss Optimal Execution
    def almgren_chriss_trajectory(
        self,
        X0: float,
        T: float,
        n_steps: int = 20,
        risk_aversion: float = 1e-6,
        temp_impact: Optional[float] = None,
        perm_impact: Optional[float] = None,
        vol: Optional[float] = None
    ) -> pd.DataFrame:
        eta = temp_impact if temp_impact else (self.eta * self.sigma_atm / np.sqrt(self.adv_vega))
        kappa_perm = perm_impact if perm_impact else eta * 0.3
        sigma = vol if vol else self.sigma_atm

        dt = T / n_steps
        tau = sigma ** 2 * risk_aversion / eta
        kappa = np.sqrt(tau)

        times = np.linspace(0, T, n_steps + 1)
        holdings = X0 * np.sinh(kappa * (T - times)) / (np.sinh(kappa * T) + 1e-15)

        trade_rates = -np.diff(holdings) / dt
        impacts = eta * trade_rates  # temporary impact per period
        perm_impacts = kappa_perm * trade_rates

        schedule = pd.DataFrame({
            'time': times[:-1],
            'holding': holdings[:-1],
            'trade_rate': trade_rates,
            'temp_impact': impacts,
            'perm_impact': perm_impacts,
            'cum_perm_cost': np.cumsum(perm_impacts * dt),
        })

        schedule['exec_cost'] = (
            eta * schedule['trade_rate'] ** 2 * dt +
            kappa_perm * schedule['trade_rate'] * schedule['holding'] * dt
        )

        return schedule

    # 4. Surface Deformation from Large Trade
    def vol_surface_deformation(
        self,
        q_vega: float,
        strikes: np.ndarray,
        T: float,
        iv_surface: np.ndarray,
        trade_K: float,
        vv_breadth: float = 0.05
    ) -> np.ndarray:
        impact_center = self.eta * self.sigma_atm * np.sqrt(abs(q_vega) / (self.adv_vega + 1e-10))
        impact_center *= np.sign(q_vega)

        # Propagation : Gaussian decay across strikes
        # Width parameter : vv_breadth * ATM IV * sqrt(T) vol-of-vol scaling
        sigma_prop = vv_breadth * self.sigma_atm * np.sqrt(T) * self.S

        delta_iv = impact_center * np.exp(-0.5 * ((strikes - trade_K) / sigma_prop) ** 2)
        return delta_iv

    # 5. Options-to-Equity Impact Propagation
    def options_to_equity_impact(
        self,
        q_contracts: float,
        K: float,
        T: float,
        iv: float,
        side: int = 1
    ) -> dict:
        """
        Compute equity market impact from option order flow (eq. 13.47).
        Accounts for immediate delta hedge + ongoing gamma rebalancing.

        Returns expected spot move and daily rebalancing flow.
        """
        T = max(T, 1e-10)
        sqrt_T = np.sqrt(T)
        d1 = (np.log(self.S / K) + (self.r + 0.5 * iv ** 2) * T) / (iv * sqrt_T)
        delta = norm.cdf(d1) if side > 0 else abs(norm.cdf(d1) - 1)
        gamma = norm.pdf(d1) / (self.S * iv * sqrt_T)

        # Shares needed to delta-hedge
        shares_hedge = q_contracts * self.m * delta * side

        # Dollar impact from delta hedge
        lambda_eq = self.S / self.adv_equity
        spot_impact_direct = lambda_eq * shares_hedge * self.S

        # Daily gamma rebalancing flow (for 1 day)
        dt = 1.0 / 252
        daily_gamma_flow = q_contracts * self.m * gamma * self.S * self.sigma_atm * np.sqrt(dt)

        return {
            'delta_hedge_shares': shares_hedge,
            'spot_impact_direct': spot_impact_direct,
            'spot_impact_pct': spot_impact_direct / self.S * 100,
            'daily_gamma_rebal': daily_gamma_flow,
            'total_5day_flow': shares_hedge + 5 * daily_gamma_flow,
            'dominant_direction': 'BUY' if shares_hedge > 0 else 'SELL'
        }

    # 6. Intraday Impact Schedule
    def intraday_impact_schedule(
        self,
        total_vega: float,
        minutes: np.ndarray = None
    ) -> pd.DataFrame:
        """
        Model intraday vol-impact variation.
        U-shaped intraday pattern: high at open/close, low at midday.

        minutes: array of minutes since market open (0 = 9:30 AM)
        """
        if minutes is None:
            minutes = np.arange(0, 390, 5)  # Every 5 min, 9:30-16:00

        # U-shape : lambda(t) = a + b*exp(-t/tau1) + c*exp(-(390-t)/tau2)
        a, b, c = 1.0, 1.5, 1.2
        tau1, tau2 = 30.0, 20.0
        intraday_multiplier = a + b * np.exp(-minutes / tau1) + c * np.exp(-(390 - minutes) / tau2)
        intraday_multiplier /= intraday_multiplier.mean()  # normalise to mean=1

        base_impact = self.eta * self.sigma_atm * np.sqrt(total_vega / (self.adv_vega * 6.5 / 24))

        df = pd.DataFrame({
            'minute': minutes,
            'time': pd.to_datetime('09:30') + pd.to_timedelta(minutes, 'm'),
            'multiplier': intraday_multiplier,
            'vol_impact': base_impact * intraday_multiplier * 100  # vol pts
        })
        return df

class OptionsVWAPOptimizer:
    """
    Compute the VWAP-optimal execution schedule for a large options block.
    Minimises market impact subject to execution completion by time T.
    """
    def __init__(self, impact_model: OptionsMarketImpact):
        self.impact = impact_model

    def optimal_schedule(
        self,
        X0_vega: float,
        T_hours: float,
        n_buckets: int = 10,
        risk_aversion: float = 1e-6,
        vol_intraday: float = 0.01
    ) -> pd.DataFrame:
        """
        Solve for optimal execution weights across time buckets.

        Minimises : sum_t [eta * x_t^2] + lambda * sum_t [sigma^2 * Q_t^2]
        s.t. sum_t x_t = X0_vega

        Parameters:
        -----------
        X0_vega : total vega-notional to execute
        T_hours : total execution window in hours
        n_buckets : number of equal time buckets
        risk_aversion : mean-variance tradeoff parameter
        vol_intraday : per-bucket vol of the position
        """
        eta = self.impact.eta * self.impact.sigma_atm / np.sqrt(self.impact.adv_vega)
        sigma = vol_intraday

        # Objective : min over weights w_t summing to 1
        # Cost = sum eta *(w_t*X0)^2 + lambda * sigma^2*(sum_{s>=t} w_s * X0)^2
        def cost(w):
            w = np.abs(w)
            w /= w.sum() + 1e-10
            x = w * X0_vega
            Q = np.cumsum(x[::-1])[::-1]  # remaining holding
            temp_cost = eta * np.sum(x ** 2)
            risk_cost = risk_aversion * sigma ** 2 * np.sum(Q ** 2)
            return temp_cost + risk_cost

        w0 = np.ones(n_buckets) / n_buckets
        res = minimize(
            cost,
            w0,
            method='SLSQP',
            constraints={'type': 'eq', 'fun': lambda w: w.sum() - 1.0},
            bounds=[(0, 1)] * n_buckets
        )

        weights = np.abs(res.x) / np.abs(res.x).sum()
        executed = weights * X0_vega

        dt = T_hours / n_buckets
        times = np.arange(n_buckets) * dt

        return pd.DataFrame({
            'bucket': np.arange(n_buckets),
            'time_hours': times,
            'weight': weights,
            'vega_executed': executed,
            'cum_vega': np.cumsum(executed),
            'impact_pts': self.impact.eta * self.impact.sigma_atm * np.sqrt(executed / (self.impact.adv_vega * dt)) * 100
        })


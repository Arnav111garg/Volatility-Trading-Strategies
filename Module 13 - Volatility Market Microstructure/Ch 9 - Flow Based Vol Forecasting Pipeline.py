class RealisedVarianceEstimator:
    """
    High-frequency realised variance estimation with noise correction.
    Implements: RV, BV (bipower), TSRV, and jump-robust estimators.
    """
    def __init__(self, sampling_freq: str = '5min'):
        self.freq = sampling_freq

    def realised_variance(self, prices: pd.Series) -> float:
        """Standard RV = sum of squared log returns."""
        log_returns = np.log(prices / prices.shift(1)).dropna()
        return float((log_returns ** 2).sum())

    def bipower_variation(self, prices: pd.Series) -> float:
        """
        Barndorff-Nielsen & Shephard (2004) Bipower Variation.
        Robust to jumps: BV = (pi / 2) * sum |r_t| * |r_{t-1}|
        """
        r = np.log(prices / prices.shift(1)).dropna().values
        bv = (np.pi / 2) * np.sum(np.abs(r[1:]) * np.abs(r[:-1]))
        return bv

    def tsrv(self, tick_prices: pd.Series, K: int = 30) -> float:
        """
        Two-Scale Realised Variance (Zhang et al., 2005).
        Noise-robust estimator using slow and fast time scales.
        K: slow-scale subsampling (every K ticks)
        """
        prices = tick_prices.values
        n = len(prices)
        log_ret = np.diff(np.log(prices))
        rv_fast = np.sum(log_ret ** 2)

        # Slow scale: average over K sub-grids
        rv_slow_list = []
        for k in range(K):
            idx = np.arange(k, n, K)
            if len(idx) >= 2:
                sub_prices = prices[idx]
                sub_ret = np.diff(np.log(sub_prices))
                rv_slow_list.append(np.sum(sub_ret ** 2))

        rv_slow = np.mean(rv_slow_list) if rv_slow_list else rv_fast
        n_bar = (n - K) / K

        # TSRV correction
        tsrv_val = rv_slow / (1 - n_bar / n) - (n_bar / n) / (1 - n_bar / n) * rv_fast
        return max(tsrv_val, 0.0)

    def jump_component(self, rv: float, bv: float, threshold: float = 0.99) -> dict:
        """
        Decompose RV into continuous + jump components (Huang & Tauchen, 2005).
        """
        from scipy.stats import chi2
        ratio = bv / rv if rv > 0 else 1.0
        jump = max(rv - bv, 0.0)
        cont = bv
        # Test statistic for jump significance
        z_stat = (rv - bv) / (rv + 1e-10)
        p_val = 1 - chi2.cdf(max(z_stat * rv * 1e6, 0), df=1)
        return {
            'rv': rv,
            'bv': bv,
            'jump': jump,
            'continuous': cont,
            'jump_pct': jump / (rv + 1e-10) * 100,
            'jump_significant': bool(p_val < (1 - threshold))
        }


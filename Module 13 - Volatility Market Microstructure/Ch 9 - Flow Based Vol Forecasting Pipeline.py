class HARGEXModel:
    def __init__(self, h: int = 1, model_type: str = 'ridge'):
        """
        h : forecast horizon in days
        model_type : 'ols', 'ridge', 'gbm'
        """
        self.h = h
        self.model_type = model_type
        self.scaler = StandardScaler()
        self.model = None
        self.feature_names = []

    def build_features(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Build HAR + microstructure feature matrix from daily data.
        """
        out = pd.DataFrame(index=df.index)

        # HAR components
        out['RV_d'] = df['rv']
        out['RV_w'] = df['rv'].rolling(5).mean()
        out['RV_m'] = df['rv'].rolling(22).mean()

        # VIX features
        if 'vix' in df.columns:
            out['VIX'] = df['vix'] / 100
            out['dVIX_1d'] = df['vix'].diff(1) / 100
            out['dVIX_5d'] = df['vix'].diff(5) / 100
            out['VIX_sq'] = (df['vix'] / 100) ** 2

        # Dealer positioning
        if 'gex' in df.columns:
            gex_z = (df['gex'] - df['gex'].rolling(60).mean()) / (df['gex'].rolling(60).std() + 1e-10)
            out['GEX_z'] = gex_z
            out['GEX_level'] = df['gex'] / 1e10
            out['dGEX_1d'] = df['gex'].diff(1) / 1e10
            out['GEX_negative'] = (df['gex'] < 0).astype(float)

        if 'vex' in df.columns:
            out['VEX_z'] = (df['vex'] - df['vex'].rolling(60).mean()) / (df['vex'].rolling(60).std() + 1e-10)

        # GEX VIX interaction
        if 'gex' in df.columns and 'vix' in df.columns:
            out['GEX_x_VIX'] = out['GEX_level'] * out['VIX']

        for col in ['flow_dafs', 'flow_vwfs', 'pcoi']:
            if col in df.columns:
                out[col] = df[col]
                out[f'{col}_5d'] = df[col].rolling(5).mean()
                out[f'{col}_sq'] = df[col] ** 2

        # Microstructure
        for col in ['bid_ask_spread', 'vpin', 'kyle_lambda']:
            if col in df.columns:
                out[col] = df[col]
                out[f'{col}_z'] = (df[col] - df[col].rolling(20).mean()) / (df[col].rolling(20).std() + 1e-10)

        # VRP feature
        if 'vix' in df.columns and 'rv' in df.columns:
            out['VRP'] = (df['vix'] / 100) ** 2 - df['rv'].rolling(21).mean()

        # Calendar
        if 'days_to_opex' in df.columns:
            out['OPEX_near'] = (df['days_to_opex'] <= 3).astype(float)
            out['OPEX_dist'] = df['days_to_opex'] / 21

        # Leverage effect proxy
        out['neg_ret'] = (df['rv'].shift(1) * (-1)).clip(lower=0)

        self.feature_names = list(out.columns)
        return out

    def fit(self, X: pd.DataFrame, y: pd.Series, n_splits: int = 5) -> dict:
        """
        Time-series cross-validated fit.
        """
        X_clean = X.dropna()
        y_clean = y.loc[X_clean.index].dropna()
        common = X_clean.index.intersection(y_clean.index)
        X_fit = X_clean.loc[common]
        y_fit = y_clean.loc[common]

        X_scaled = self.scaler.fit_transform(X_fit)

        if self.model_type == 'ridge':
            self.model = Ridge(alpha=1.0)
        elif self.model_type == 'gbm':
            self.model = GradientBoostingRegressor(
                n_estimators=300, max_depth=4,
                learning_rate=0.03, subsample=0.8,
                min_samples_leaf=10
            )
        else:
            from sklearn.linear_model import LinearRegression
            self.model = LinearRegression()

        # Walk-forward cross-validation
        tscv = TimeSeriesSplit(n_splits=n_splits, gap=self.h)
        cv_mse = []
        for train_idx, val_idx in tscv.split(X_scaled):
            Xtr, Xval = X_scaled[train_idx], X_scaled[val_idx]
            ytr, yval = y_fit.iloc[train_idx], y_fit.iloc[val_idx]
            self.model.fit(Xtr, ytr)
            pred = self.model.predict(Xval)
            cv_mse.append(mean_squared_error(yval, pred))

        # Final fit
        self.model.fit(X_scaled, y_fit)
        fitted = self.model.predict(X_scaled)

        # Feature importance
        if hasattr(self.model, 'feature_importances_'):
            importance = pd.Series(self.model.feature_importances_, index=self.feature_names).sort_values(ascending=False)
        elif hasattr(self.model, 'coef_'):
            importance = pd.Series(
                np.abs(self.model.coef_) / (np.abs(self.model.coef_).sum() + 1e-10),
                index=self.feature_names
            ).sort_values(ascending=False)
        else:
            importance = pd.Series(dtype=float)

        return {
            'cv_rmse': np.sqrt(np.mean(cv_mse)),
            'cv_mse_std': np.std(cv_mse),
            'in_sample_r2': 1 - mean_squared_error(y_fit, fitted) / (y_fit.var() + 1e-10),
            'feature_importance': importance,
            'n_obs': len(y_fit)
        }

    def predict(self, X: pd.DataFrame) -> pd.Series:
        X_clean = X.dropna()
        X_scaled = self.scaler.transform(X_clean)
        preds = self.model.predict(X_scaled)
        return pd.Series(np.sqrt(np.maximum(preds, 0) * 252), index=X_clean.index, name=f'vol_forecast_h{self.h}')

class VRPAnalyser:
    """
    Variance Risk Premium computation, decomposition, and signal generation.
    """
    def compute_vrp(self, vix: pd.Series, rv: pd.Series, horizon: int = 21) -> pd.Series:
        vix_var = (vix / 100) ** 2
        rv_fwd = rv.rolling(horizon).mean().shift(-horizon)
        vrp = vix_var - rv_fwd
        return vrp.rename('VRP')

    def vrp_z_score(self, vrp: pd.Series, window: int = 252) -> pd.Series:
        return ((vrp - vrp.rolling(window).mean()) / (vrp.rolling(window).std() + 1e-10)).rename('VRP_z')

    def vrp_regime_classifier(self, vrp_z: pd.Series) -> pd.Series:
        conditions = [
            vrp_z > 1.5,
            vrp_z > 0.5,
            vrp_z < -1.5,
            vrp_z < -0.5
        ]
        choices = ['STRONGLY_ELEVATED', 'ELEVATED', 'COMPRESSED', 'SLIGHTLY_COMPRESSED']
        return pd.Series(np.select(conditions, choices, default='NORMAL'), index=vrp_z.index, name='VRP_regime')

    def gex_vrp_decomposition(self, vrp: pd.Series, gex: pd.Series, pcoi: pd.Series) -> dict:
        df = pd.DataFrame({'vrp': vrp, 'gex': gex / 1e10, 'pcoi': pcoi}).dropna()
        X = np.column_stack([np.ones(len(df)), df['gex'], df['pcoi']])
        y = df['vrp'].values

        beta, _, _, _ = np.linalg.lstsq(X, y, rcond=None)
        fitted = X @ beta
        residual = y - fitted

        return {
            'alpha': beta[0],
            'beta_gex': beta[1],
            'beta_pcoi': beta[2],
            'r_squared': 1 - np.var(residual) / (np.var(y) + 1e-10),
            'vrp_gex_comp': beta[1] * df['gex'],
            'vrp_flow_comp': beta[2] * df['pcoi'],
            'vrp_residual': pd.Series(residual, index=df.index)
        }


def demo_har_gex_forecast(n_obs: int = 1000):
    rng = np.random.default_rng(42)

    gex = np.zeros(n_obs)
    gex[0] = 2e9
    for t in range(1, n_obs):
        gex[t] = (0.95 * gex[t-1]
                  + rng.normal(0, 5e8)
                  + rng.choice([-1e10, 0, 1e10], p=[0.02, 0.96, 0.02]))

    rv = np.maximum(0.0001 + 0.0003 * rng.standard_normal(n_obs)
                    - 0.00002 * gex / 1e10
                    + 0.6 * np.abs(rng.standard_normal(n_obs)) * 0.0002, 1e-6)

    vix = np.sqrt(rv * 252 * 1.1 + rng.uniform(0.001, 0.003, n_obs)) * 100
    flow = rng.standard_normal(n_obs) * 0.3 + 0.1 * np.sign(gex)
    pcoi = np.clip(rng.normal(0.1, 0.3, n_obs), -1, 1)

    idx = pd.date_range('2015-01-01', periods=n_obs, freq='B')
    df = pd.DataFrame({'rv': rv, 'gex': gex, 'vix': vix, 'flow_dafs': flow, 'pcoi': pcoi}, index=idx)
    df['target'] = df['rv'].shift(-1)

    har = HARGEXModel(h=1, model_type='gbm')
    features = har.build_features(df)
    common = features.dropna().index.intersection(df['target'].dropna().index)

    results = har.fit(features.loc[common], df['target'].loc[common])

    print("=" * 55)
    print(" HAR-GEX FORECAST RESULTS ")
    print("=" * 55)
    print(f" CV RMSE : {results['cv_rmse']:.6f}")
    print(f" In-sample R2 : {results['in_sample_r2']:.3f}")
    print(f" Observations : {results['n_obs']}")
    print("\n Top 10 Feature Importances :")
    for feat, imp in results['feature_importance'].head(10).items():
        bar = '*' * int(imp * 30)
        print(f" {feat:20s} {imp:.4f} {bar}")

    return har, results


import numpy as np
import pandas as pd
from scipy.stats import norm

def bs_greeks(S, K, T, r, sigma, option_type='call'):
    if T <= 1e-10:
        # At expiry: intrinsic value only
        intrinsic = max(S - K, 0.0) if option_type == 'call' else max(K - S, 0.0)
        delta = 1.0 if (S > K and option_type == 'call') else (-1.0 if (S < K and option_type == 'put') else 0.0)
        return {
            'price': intrinsic,
            'delta': delta,
            'gamma': 0.0,
            'vega': 0.0,
            'theta': 0.0,
            'rho': 0.0
        }

    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)

    pdf_d1 = norm.pdf(d1)

    if option_type == 'call':
        price = S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
        delta = norm.cdf(d1)
        rho = K * T * np.exp(-r * T) * norm.cdf(d2)
    else:
        price = K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)
        delta = norm.cdf(d1) - 1.0
        rho = -K * T * np.exp(-r * T) * norm.cdf(-d2)

    gamma = pdf_d1 / (S * sigma * np.sqrt(T))

    # Vega: dV/d(sigma) - per 1% change in vol
    vega = S * pdf_d1 * np.sqrt(T) / 100.0

    # Theta: dV/dt (per day)
    if option_type == 'call':
        theta = (-(S * pdf_d1 * sigma) / (2.0 * np.sqrt(T)) - r * K * np.exp(-r * T) * norm.cdf(d2)) / 365.0
    else:
        theta = (-(S * pdf_d1 * sigma) / (2.0 * np.sqrt(T)) + r * K * np.exp(-r * T) * norm.cdf(-d2)) / 365.0

    return {
        'price': price,
        'delta': delta,
        'gamma': gamma,
        'vega': vega,
        'theta': theta,
        'rho': rho
    }

class DealerInventoryTracker:
    def __init__(self, S: float, r: float = 0.05, multiplier: int = 100):
        self.S = S          # Current spot price
        self.r = r          # Risk-free rate
        self.m = multiplier # Contract multiplier

    def compute_book_greeks(self, options_df: pd.DataFrame) -> dict:
        results = []

        for _, row in options_df.iterrows():
            g = bs_greeks(
                S=self.S,
                K=row['strike'],
                T=row['expiry_T'],
                r=self.r,
                sigma=row['iv'],
                option_type=row['option_type']
            )

            # Dealer sign: positive = dealer is long this option
            quantity = row['oi'] * row['dealer_sign']

            results.append({
                'strike': row['strike'],
                'expiry_T': row['expiry_T'],
                'option_type': row['option_type'],
                'delta_contribution': quantity * g['delta'] * self.m * self.S,
                'gamma_contribution': quantity * g['gamma'] * self.m * (self.S**2),
                'vega_contribution': quantity * g['vega'] * self.m,
                'theta_contribution': quantity * g['theta'] * self.m,
                'dollar_gamma': g['gamma'] * self.m * (self.S**2), # per contract
                'gamma_raw': g['gamma'],
                'delta_raw': g['delta'],
                'oi': row['oi']
            })

        df = pd.DataFrame(results)

        return {
            'DEX': df['delta_contribution'].sum(),
            'GEX': df['gamma_contribution'].sum(),
            'VEX': df['vega_contribution'].sum(),
            'TEX': df['theta_contribution'].sum(),
            'detail': df
        }

    def gex_by_strike(self, options_df: pd.DataFrame) -> pd.DataFrame:
        book = self.compute_book_greeks(options_df)
        return (book['detail']
                .groupby('strike')['gamma_contribution']
                .sum()
                .reset_index()
                .rename(columns={'gamma_contribution': 'GEX'}))

    def gex_by_expiry(self, options_df: pd.DataFrame) -> pd.DataFrame:
        book = self.compute_book_greeks(options_df)
        return (book['detail']
                .groupby('expiry_T')['gamma_contribution']
                .sum()
                .reset_index()
                .rename(columns={'gamma_contribution': 'GEX'}))

def example_dealer_tracker():
    S = 4500.0
    r = 0.05
    T = 30.0 / 365.0

    options = pd.DataFrame([
        {'strike': 4500, 'expiry_T': T, 'iv': 0.18, 'oi': 50000, 'option_type': 'put', 'dealer_sign': -1},
        {'strike': 4500, 'expiry_T': T, 'iv': 0.17, 'oi': 30000, 'option_type': 'call', 'dealer_sign': -1},
        {'strike': 4300, 'expiry_T': T, 'iv': 0.22, 'oi': 80000, 'option_type': 'put', 'dealer_sign': -1},
        {'strike': 4200, 'expiry_T': T, 'iv': 0.25, 'oi': 40000, 'option_type': 'put', 'dealer_sign': -1},
        {'strike': 4700, 'expiry_T': T, 'iv': 0.16, 'oi': 25000, 'option_type': 'call', 'dealer_sign': 1},
        {'strike': 4800, 'expiry_T': T, 'iv': 0.155, 'oi': 15000, 'option_type': 'call', 'dealer_sign': 1}
    ])

    tracker = DealerInventoryTracker(S=S, r=r)
    book = tracker.compute_book_greeks(options)

    print("=" * 55)
    print(f"DEALER INVENTORY SUMMARY | SPX @ {S}")
    print("=" * 55)
    print(f"DEX (Dollar Delta): ${book['DEX']:>15,.0f}")
    print(f"GEX (Dollar Gamma): ${book['GEX']:>15,.0f}")
    print(f"VEX (Dollar Vega):  ${book['VEX']:>15,.0f}")
    print(f"TEX (Dollar Theta): ${book['TEX']:>15,.0f}")
    print()

    g_strike = tracker.gex_by_strike(options)
    print("GEX by Strike:")
    for _, row in g_strike.iterrows():
        val = row['GEX']
        bar_len = int(abs(val) / 1e6)
        sign = '+' if val > 0 else '-'
        print(f" K={row['strike']:.0f} {sign}{'|' * min(bar_len, 40):<40} ${val/1e6:>6.1f}M")

    return book

if __name__ == "__main__":
    example_dealer_tracker()


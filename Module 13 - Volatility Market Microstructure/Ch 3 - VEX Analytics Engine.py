import numpy as np
import pandas as pd
from scipy.stats import norm
from typing import Tuple, Dict, Optional

def bs_vega_volga(S: float, K: float, T: float, r: float, sigma: float) -> Tuple[float, float]:
    T = max(T, 1e-10)
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)

    vega_raw = S * np.sqrt(T) * norm.pdf(d1) # per unit sigma
    vega_pct = vega_raw / 100.0              # per 1% change
    volga = vega_raw * d1 * d2 / sigma
    return vega_pct, volga

class VEXAnalytics:
    def __init__(self, S: float, r: float = 0.05, m: int = 100):
        self.S = S
        self.r = r
        self.m = m

    def compute_vex(self, chain: pd.DataFrame) -> Dict:
        records = []
        for _, row in chain.iterrows():
            vega, volga = bs_vega_volga(
                self.S,
                row['strike'],
                row['expiry_T'],
                self.r,
                row['iv']
            )

            net_qty = row['oi'] * row['dealer_sign'] * self.m
            records.append({
                'strike': row['strike'],
                'expiry_T': row['expiry_T'],
                'option_type': row['option_type'],
                'vega_unit': vega,
                'volga_unit': volga,
                'vex_contrib': net_qty * vega,       # $ per 1% vol move
                'vegex_contrib': net_qty * volga,     # $ per 1% vol-of-vol
                'oi': row['oi'],
                'iv': row['iv']
            })

        df = pd.DataFrame(records)

        buckets = {
            '0-7d': (0, 7/365),
            '8-30d': (7/365, 30/365),
            '31-90d': (30/365, 90/365),
            '91-180d': (90/365, 180/365),
            '180d+': (180/365, np.inf)
        }

        vex_by_bucket = {}
        for name, (t_min, t_max) in buckets.items():
            mask = (df['expiry_T'] > t_min) & (df['expiry_T'] <= t_max)
            vex_by_bucket[name] = df[mask]['vex_contrib'].sum()

        return {
            'total_vex': df['vex_contrib'].sum(),
            'total_vegex': df['vegex_contrib'].sum(),
            'vex_by_bucket': vex_by_bucket,
            'vex_by_strike': df.groupby('strike')['vex_contrib'].sum().to_dict(),
            'vex_by_expiry': df.groupby('expiry_T')['vex_contrib'].sum().to_dict(),
            'detail': df
        }

    def vol_cascade_risk(self, vex_result: Dict, delta_vix: float = 5.0, market_vol_supply: float = 5e8) -> Dict:
        total_vex = vex_result['total_vex']
        total_vegex = vex_result['total_vegex']

        # First-order P&L from VEX
        vol_pnl = total_vex * delta_vix
        # Second-order (volga) contribution
        vol_pnl_2nd = 0.5 * total_vegex * delta_vix**2
        total_pnl = vol_pnl + vol_pnl_2nd

        # If dealers are short vega (VEX < 0) and VIX rises:
        # they suffer losses and must buy vega back
        if total_vex < 0 and delta_vix > 0:
            forced_buyback_vega = abs(total_vex * delta_vix)
            implied_vol_amplification = forced_buyback_vega / market_vol_supply
            cascade_factor = 1.0 + implied_vol_amplification
        else:
            cascade_factor = 1.0
            implied_vol_amplification = 0.0

        return {
            'vol_pnl_1st_order': vol_pnl,
            'vol_pnl_2nd_order': vol_pnl_2nd,
            'total_vol_pnl': total_pnl,
            'cascade_factor': cascade_factor,
            'amplified_vix_move': delta_vix * cascade_factor,
            'regime': 'VOL CASCADE RISK' if cascade_factor > 1.3 else 'NORMAL'
        }

    def vex_mean_reversion_speed(self, vex_total: float, kappa_0: float = 5.0, eta: float = 0.1, liquidity: float = 1e9) -> float:
        """
        Compute effective vol mean-reversion speed.
        """
        return kappa_0 + eta * vex_total / liquidity


import numpy as np
import pandas as pd
from scipy.stats import norm
import matplotlib.pyplot as plt
from scipy.interpolate import RectBivariateSpline

class GEXAnalytics:
    """
    Full GEX computation engine with surface integration,
    Zero Gamma Level detection, and regime classification.
    """
    def __init__(self, S: float, r: float = 0.05, multiplier: int = 100):
        self.S = S
        self.r = r
        self.m = multiplier

    @staticmethod
    def bs_gamma(S, K, T, r, sigma):
        """BSM gamma, vectorised."""
        T = np.maximum(T, 1e-10)
        d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
        return norm.pdf(d1) / (S * sigma * np.sqrt(T))

    def compute_gex(self, chain: pd.DataFrame, spot_range=None) -> dict:
        """
        Full GEX computation from options chain.

        chain: DataFrame with columns:
               strike, expiry_T, option_type ('call'/'put'), oi, iv
        spot_range: array-like of spot prices for GEX profile

        Returns dict with:
        'total_gex' : float (dollars)
        'gex_by_strike' : DataFrame
        'gex_by_expiry' : DataFrame
        'gex_profile' : DataFrame (if spot_range provided)
        'zero_gamma_level' : float
        """
        df = chain.copy()

        # Compute gamma for each contract at current spot
        df['gamma'] = self.bs_gamma(self.S, df['strike'], df['expiry_T'], self.r, df['iv'])

        # Dollar gamma per contract (OI * gamma * m * S ^2)
        df['dollar_gamma'] = df['gamma'] * self.m * self.S ** 2

        # Dealer sign: long calls (OI * +1), long puts (OI * -1)
        # Convention: positive OI = dealer SHORT option (sold to customer)
        df['dealer_sign'] = np.where(df['option_type'] == 'call', 1.0, -1.0)
        df['gex'] = df['dealer_sign'] * df['oi'] * df['dollar_gamma']

        total_gex = df['gex'].sum()

        # GEX by strike
        gex_strike = (df.groupby('strike')['gex']
                      .sum()
                      .reset_index()
                      .rename(columns={'gex': 'GEX'}))

        # GEX by expiry
        gex_expiry = (df.groupby('expiry_T')['gex']
                      .sum()
                      .reset_index()
                      .rename(columns={'gex': 'GEX'}))

        # GEX Profile over spot_range
        gex_profile = None
        zero_gamma_level = np.nan
        if spot_range is not None:
            profile_results = []
            for spot in spot_range:
                gammas = self.bs_gamma(spot, df['strike'], df['expiry_T'], self.r, df['iv'])
                dollar_gammas = gammas * self.m * spot ** 2
                gex_vals = df['dealer_sign'] * df['oi'] * dollar_gammas
                profile_results.append({'spot': spot, 'GEX': gex_vals.sum()})
            gex_profile = pd.DataFrame(profile_results)

            # Detect Zero Gamma Level (where profile crosses 0)
            gex_signs = np.sign(gex_profile['GEX'].values)
            sign_changes = np.diff(gex_signs)
            idx_cross = np.where(sign_changes != 0)[0]
            if len(idx_cross) > 0:
                # Use linear interpolation near the first crossing point
                idx = idx_cross[0]
                x0, x1 = gex_profile['spot'].values[idx], gex_profile['spot'].values[idx + 1]
                y0, y1 = gex_profile['GEX'].values[idx], gex_profile['GEX'].values[idx + 1]
                zero_gamma_level = x0 - y0 * (x1 - x0) / (y1 - y0)

        return {
            'total_gex': total_gex,
            'gex_by_strike': gex_strike,
            'gex_by_expiry': gex_expiry,
            'gex_profile': gex_profile,
            'zero_gamma_level': zero_gamma_level,
            'regime': self._classify_regime(total_gex)
        }

    @staticmethod
    def _classify_regime(gex: float) -> str:
        """Classify GEX into market regime."""
        gex_bn = gex / 1e9
        if gex_bn > 10.0:
            return "STRONGLY POSITIVE (pin / squeeze risk)"
        elif gex_bn > 2.0:
            return "POSITIVE (dampened vol)"
        elif gex_bn > -2.0:
            return "NEUTRAL"
        elif gex_bn > -8.0:
            return "NEGATIVE (elevated vol)"
        else:
            return "STRONGLY NEGATIVE (crash / unwind risk)"

    def plot_gex_profile(self, result: dict, figsize=(14, 6)):
        """Plot GEX profile with regime zones."""
        if result.get('gex_profile') is None:
            raise ValueError("Run compute_gex with spot_range to get profile")

        profile = result['gex_profile']
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=figsize)

        # Left panel: GEX profile vs spot
        ax1.fill_between(profile['spot'], profile['GEX'] / 1e9, 0,
                         where=(profile['GEX'] > 0), alpha=0.3, color='green', label='Long gamma (stabilising)')
        ax1.fill_between(profile['spot'], profile['GEX'] / 1e9, 0,
                         where=(profile['GEX'] < 0), alpha=0.3, color='red', label='Short gamma (destabilising)')
        ax1.plot(profile['spot'], profile['GEX'] / 1e9, 'b-', linewidth=2)
        ax1.axhline(0, color='black', linewidth=1, linestyle='--')
        ax1.axvline(self.S, color='green', linewidth=1.5, linestyle=':', label=f'Spot = {self.S}')

        if not np.isnan(result['zero_gamma_level']):
            ax1.axvline(result['zero_gamma_level'], color='red', linewidth=1.5, linestyle=':',
                        label=f"ZGL = {result['zero_gamma_level']:.0f}")

        ax1.set_xlabel('Spot Price')
        ax1.set_ylabel('GEX ($bn)')
        ax1.set_title('GEX Profile vs Spot')
        ax1.legend(fontsize=8)
        ax1.grid(True, alpha=0.3)

        # Right panel: GEX by strike
        gex_k = result['gex_by_strike']
        colors = ['green' if x > 0 else 'red' for x in gex_k['GEX']]
        ax2.bar(gex_k['strike'], gex_k['GEX'] / 1e6, color=colors, alpha=0.7,
                width=(gex_k['strike'].max() - gex_k['strike'].min()) / len(gex_k) * 0.8)
        ax2.axhline(0, color='black', linewidth=1)
        ax2.set_xlabel('Strike')
        ax2.set_ylabel('GEX ($M)')
        ax2.set_title('GEX by Strike')
        ax2.grid(True, alpha=0.3, axis='y')

        plt.tight_layout()
        plt.suptitle(f'GEX Analysis | Total: ${result["total_gex"]/1e9:.2f}bn | Regime: {result["regime"]}',
                     fontsize=10, y=1.01, fontweight='bold')
        return fig

def gex_vol_forecast(gex_total: float, vix: float, market_depth: float = 5e10) -> dict:
    """
    Forecast intraday realised vol using GEX adjustment formula.
    """
    sigma_0 = vix / 100.0 / np.sqrt(252) # Daily vol from VIX

    if gex_total >= 0:
        damping = 1.0 - gex_total / (gex_total + market_depth)
    else:
        amplification = 1.0 + abs(gex_total) / market_depth
        damping = amplification

    sigma_adj = sigma_0 * np.sqrt(damping)

    return {
        'vix': vix,
        'gex_bn': gex_total / 1e9,
        'sigma_0_daily': sigma_0 * 100,
        'sigma_adj_daily': sigma_adj * 100,
        'sigma_adj_annual': sigma_adj * np.sqrt(252) * 100,
        'damping_factor': damping,
        'regime': 'stabilising' if gex_total > 0 else 'destabilising'
    }


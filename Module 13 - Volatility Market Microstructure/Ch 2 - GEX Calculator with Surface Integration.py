# Initialize the analytics engine for a spot price of 4500.0
S_spot = 4500.0
analytics = GEXAnalytics(S=S_spot, r=0.05)

# Define a synthetic option chain around the spot price of 4500
strikes = [4200, 4300, 4400, 4500, 4600, 4700, 4800]
options_data = []

for k in strikes:
    # ATM / OTM Puts (dealers short put premium)
    options_data.append({
        'strike': k,
        'expiry_T': 30.0 / 365.0,
        'option_type': 'put',
        'oi': 80000 if k < 4500 else (50000 if k == 4500 else 10000),
        'iv': 0.25 - 0.0001 * (k - 4500) # Vol skew
    })
    # ATM / OTM Calls (dealers long wing calls, short ATM)
    options_data.append({
        'strike': k,
        'expiry_T': 30.0 / 365.0,
        'option_type': 'call',
        'oi': 20000 if k < 4500 else (40000 if k == 4500 else 60000),
        'iv': 0.21 - 0.0001 * (k - 4500)
    })

chain_df = pd.DataFrame(options_data)

# Define spot range for profile calculation
spot_range = np.linspace(4000.0, 5000.0, 100)

# Compute GEX and Zero Gamma Level
gex_results = analytics.compute_gex(chain_df, spot_range=spot_range)

# Plot GEX Profile & Strike Distribution
fig = analytics.plot_gex_profile(gex_results)
plt.show()


import numpy as np
import pandas as pd
from scipy.stats import norm

class GammaSqueezeMonitor:
    """
    Real-time gamma squeeze risk monitoring system.
    Detects pre-squeeze conditions and quantifies squeeze magnitude.
    """
    def __init__(self, m: int = 100):
        self.m = m

    def bs_gamma(self, S, K, T, r, sigma):
        T = np.maximum(T, 1e-10)
        d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
        return norm.pdf(d1) / (S * sigma * np.sqrt(T))

    def compute_squeeze_metrics(
        self,
        options_df: pd.DataFrame,
        S: float,
        r: float,
        adv: float,
        short_interest: float,
        float_shares: float
    ) -> dict:
        df = options_df.copy()

        # Compute gammas
        df['gamma'] = self.bs_gamma(S, df['strike'], df['expiry_T'], r, df['iv'])
        df['dollar_gamma'] = df['gamma'] * self.m * S ** 2
        df['dealer_sign'] = np.where(df['option_type'] == 'call', 1.0, -1.0)
        df['gex'] = df['dealer_sign'] * df['oi'] * df['dollar_gamma']

        total_gex = df['gex'].sum()

        # --- Component 1: GEX/ADV ---
        gex_to_adv = abs(total_gex) / (adv * S)

        # --- Component 2: Call OI Surge ---
        call_oi = df[df['option_type'] == 'call']['oi'].sum()
        put_oi = df[df['option_type'] == 'put']['oi'].sum()
        call_dominance = call_oi / (call_oi + put_oi + 1)

        # --- Component 3: Effective vol amplification ---
        # Market resilience proxy: ADV * 0.1 (10% of daily vol)
        lambda_mkt = adv * 0.10  # shares per unit price move
        gamma_D = abs(total_gex) / (S ** 2 * self.m)  # total dealer gamma in shares

        sar = 1.0 / max(abs(1.0 - gamma_D / (lambda_mkt + 1e-10)), 0.1)
        sar = min(sar, 20.0)  # Cap at 20x for numerical stability

        # --- Component 4: Short interest ---
        short_pct = short_interest / (float_shares + 1e-10)

        # --- GSRS Composite ---
        w1, w2, w3, w4 = 0.40, 0.20, 0.25, 0.15
        gsrs = (
            w1 * min(gex_to_adv * 10, 5.0) +
            w2 * min(call_dominance * 4, 4.0) +
            w3 * min((sar - 1.0), 3.0) +
            w4 * min(short_pct * 4, 3.0)
        )

        # --- Squeeze by expiry ---
        by_expiry = df.groupby('expiry_T').agg(
            gex=('gex', 'sum'),
            call_oi=('oi', lambda x: x[df.loc[x.index, 'option_type'] == 'call'].sum())
        ).reset_index()

        by_expiry['ecm'] = (
            abs(by_expiry['gex']) / (adv * S) /
            np.sqrt(np.maximum(by_expiry['expiry_T'] * 365, 1))
        )

        return {
            'total_gex': total_gex,
            'gex_to_adv': gex_to_adv,
            'call_dominance': call_dominance,
            'sar': sar,
            'short_pct': short_pct,
            'gsrs': gsrs,
            'risk_level': self._classify_risk(gsrs),
            'by_expiry': by_expiry,
            'lambda_crit': gamma_D / lambda_mkt,
            'squeeze_active': (sar > 3.0) and (total_gex < 0)
        }

    def simulate_squeeze(
        self, S0: float, sigma0: float, gamma_D: float, lambda_mkt: float,
        mu: float = 0.0, dt: float = 1/252, T: float = 10/252, n_sims: int = 1000
    ) -> np.ndarray:
        """
        Monte Carlo simulation of spot path under gamma squeeze dynamics.
        """
        n_steps = max(int(T / dt), 1)
        paths = np.zeros((n_sims, n_steps + 1))
        paths[:, 0] = S0

        for i in range(n_steps):
            # Current effective vol
            feedback_ratio = gamma_D / (lambda_mkt + 1e-10)
            sigma_eff = sigma0 / max(abs(1.0 - feedback_ratio), 0.1)
            sigma_eff = min(sigma_eff, 5.0)  # cap at 500% annual vol

            z = np.random.standard_normal(n_sims)
            dS = (mu * dt + sigma_eff * np.sqrt(dt) * z)
            paths[:, i + 1] = paths[:, i] * np.exp(dS)

            # As price rises, gamma_D increases (feedback loop)
            gamma_D *= (paths[:, i + 1] / paths[:, i]).mean()

        return paths

    @staticmethod
    def _classify_risk(gsrs: float) -> str:
        if gsrs < 1.0: return "LOW"
        elif gsrs < 1.5: return "MODERATE"
        elif gsrs < 2.0: return "ELEVATED"
        elif gsrs < 2.5: return "HIGH"
        else: return "EXTREME SQUEEZE IMMINENT"


import numpy as np
import pandas as pd
from scipy.stats import norm, nbinom
from scipy.optimize import brentq
from collections import deque
import warnings

class OptionsFlowAnalyser:
    def __init__(self, S: float, r: float = 0.05, m: int = 100, lookback_vol: int = 21, uoa_pvalue: float = 0.01):
        self.S = S
        self.r = r
        self.m = m
        self.lookback = lookback_vol
        self.uoa_threshold = uoa_pvalue
        self.trade_history = []
        self.volume_history = {}  # symbol -> deque (maxlen = 21)

    @staticmethod
    def bs_greeks_vec(S, K, T, r, sigma, option_type):
        """ Vectorised BSM greeks for arrays. """
        T = np.maximum(T, 1e-10)
        d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
        d2 = d1 - sigma * np.sqrt(T)
        delta = np.where(option_type == 'call', norm.cdf(d1), norm.cdf(d1) - 1)
        gamma = norm.pdf(d1) / (S * sigma * np.sqrt(T))
        vega = S * np.sqrt(T) * norm.pdf(d1) / 100.0
        return delta, gamma, vega

    def classify_trade(self, trade_price: float, bid: float, ask: float, prev_price: float = None) -> int:
        """
        Lee-Ready algorithm: returns +1 (buy) or -1 (sell).
        """
        mid = (bid + ask) / 2.0
        if trade_price > mid:
            return +1
        elif trade_price < mid:
            return -1
        else:  # Quote midpoint: use tick test
            if prev_price is not None:
                if trade_price > prev_price:
                    return +1
                elif trade_price < prev_price:
                    return -1
            return 0  # Cannot classify

    def process_trade_stream(self, trades_df: pd.DataFrame) -> pd.DataFrame:
        """
        Process a stream of trades and compute flow metrics.

        trades_df columns:
        timestamp, symbol, strike, expiry_T, option_type,
        trade_price, bid, ask, quantity, prev_price, iv
        """
        df = trades_df.copy()

        # Step 1: Classify each trade
        df['sign'] = df.apply(
            lambda r: self.classify_trade(r['trade_price'], r['bid'], r['ask'], r.get('prev_price')),
            axis=1
        )
        df = df[df['sign'] != 0]  # Remove unclassifiable

        # Step 2: Compute Greeks
        df['delta'], df['gamma'], df['vega'] = self.bs_greeks_vec(
            self.S, df['strike'].values, df['expiry_T'].values,
            self.r, df['iv'].values, df['option_type'].values
        )

        # Step 3: Dollar premium
        df['dollar_premium'] = df['trade_price'] * df['quantity'] * self.m
        df['signed_premium'] = df['sign'] * df['dollar_premium']
        df['signed_delta_flow'] = df['sign'] * df['delta'] * df['quantity']
        df['signed_vega_flow'] = df['sign'] * df['vega'] * df['quantity']
        df['long_vol_sign'] = df['sign']  # +1 if buying options (long vol)
        df['signed_vol_flow'] = df['long_vol_sign'] * df['vega'] * df['quantity']

        return df

    def compute_flow_signals(self, processed_df: pd.DataFrame) -> dict:
        """
        Compute aggregate flow signals over the processed trade stream.
        """
        df = processed_df

        # DAFS: Delta-Adjusted Flow Signal
        total_signed_delta = df['signed_delta_flow'].sum()
        total_abs_flow = df['quantity'].sum()
        dafs = total_signed_delta / (total_abs_flow + 1e-10)

        # VWFS: Vega-Weighted Flow Signal
        total_signed_vega = df['signed_vega_flow'].sum()
        total_abs_vega = (df['vega'] * df['quantity']).sum()
        vwfs = total_signed_vega / (total_abs_vega + 1e-10)

        # PCOI: Put-Call Order Imbalance
        call_buy_vol = df[(df['option_type'] == 'call') & (df['sign'] == +1)]['quantity'].sum()
        put_buy_vol = df[(df['option_type'] == 'put') & (df['sign'] == +1)]['quantity'].sum()
        pcoi = (put_buy_vol - call_buy_vol) / (put_buy_vol + call_buy_vol + 1e-10)

        # Net Options Premium (NOP)
        nop = df['signed_premium'].sum()

        # VPIN: Volume-synchronised PIN
        buy_vol = df[df['sign'] == +1]['quantity'].sum()
        sell_vol = df[df['sign'] == -1]['quantity'].sum()
        vpin = abs(buy_vol - sell_vol) / (buy_vol + sell_vol + 1e-10)

        # Dominant expiry
        by_expiry = (
            df.groupby('expiry_T')
            .agg({'dollar_premium': 'sum', 'quantity': 'sum'})
            .sort_values('dollar_premium', ascending=False)
        )

        return {
            'DAFS': dafs,                     # [-1, +1] directional
            'VWFS': vwfs,                     # [-1, +1] vol direction
            'PCOI': pcoi,                     # [-1, +1] put-call imbalance
            'NOP': nop,                       # dollar net premium
            'VPIN': vpin,                     # [0, 1] informed trading proxy
            'total_call_vol': df[df['option_type'] == 'call']['quantity'].sum(),
            'total_put_vol': df[df['option_type'] == 'put']['quantity'].sum(),
            'total_premium': df['dollar_premium'].sum(),
            'dominant_expiry': by_expiry.index[0] if len(by_expiry) > 0 else None,
            'flow_direction': self._interpret_signals(dafs, vwfs, pcoi, vpin)
        }

    def detect_unusual_activity(self, symbol_trades: pd.DataFrame, vol_history: pd.Series) -> pd.DataFrame:
        """
        Detect statistically unusual options activity.
        """
        alerts = []

        # Fit Negative Binomial to historical volume
        mu = vol_history.mean()
        var = vol_history.var()

        if var <= mu or mu < 1:
            return pd.DataFrame()

        r_nb = mu ** 2 / (var - mu )  # size parameter
        p_nb = r_nb / (r_nb + mu)     # success probability

        today_vol = symbol_trades['quantity'].sum()

        # P-value : probability of observing >= today_vol
        p_value = 1 - nbinom.cdf(today_vol - 1, r_nb, p_nb)

        if p_value < self.uoa_threshold:
            alerts.append({
                'volume': today_vol,
                'mean_vol': mu,
                'vol_ratio': today_vol / mu,
                'p_value': p_value,
                'premium': symbol_trades['dollar_premium'].sum(),
                'sign_bias': symbol_trades['sign'].mean(),
                'is_unusual': True
            })

        return pd.DataFrame(alerts)

    def flow_momentum(self, processed_df: pd.DataFrame, windows: list = [5, 15, 30]) -> dict:
        """
        Compute flow momentum at multiple time windows (in minutes).
        """
        df = processed_df.copy()
        df = df.sort_values('timestamp')

        results = {}
        t_max = df['timestamp'].max()

        for w in windows:
            recent_mask = (df['timestamp'] >= t_max - pd.Timedelta(minutes=w))
            recent_flow = df[recent_mask]

            nop_w = recent_flow['signed_premium'].sum()
            delta_w = recent_flow['signed_delta_flow'].sum()
            results[f'NOP_{w}min'] = nop_w
            results[f'DAFS_{w}min'] = delta_w / (recent_flow['quantity'].sum() + 1e-10)

        if len(windows) >= 2:
            short = results.get(f'DAFS_{windows[0]}min', 0)
            longer = results.get(f'DAFS_{windows[-1]}min', 0)
            results['flow_acceleration'] = short - longer

        return results

    @staticmethod
    def _interpret_signals(dafs, vwfs, pcoi, vpin) -> str:
        """Human-readable flow interpretation."""
        signals = []
        if dafs > 0.3:
            signals.append("BULLISH delta flow")
        elif dafs < -0.3:
            signals.append("BEARISH delta flow")

        if vwfs > 0.2:
            signals.append("Vol BID (buying vol)")
        elif vwfs < -0.2:
            signals.append("Vol OFFERED (selling vol)")

        if pcoi > 0.4:
            signals.append("PUT dominance (protection)")
        elif pcoi < -0.4:
            signals.append("CALL dominance (speculation)")

        if vpin > 0.7:
            signals.append("HIGH informed-trade probability")

        return " | ".join(signals) if signals else "NEUTRAL / MIXED"


def compute_iv_spread_signal(options_df: pd.DataFrame) -> pd.Series:
    calls = options_df[options_df['option_type'] == 'call'].copy()
    puts = options_df[options_df['option_type'] == 'put'].copy()

    merged = calls.merge(puts, on=['symbol', 'strike', 'expiry_T'], suffixes=('_call', '_put'))
    merged['iv_spread'] = merged['iv_call'] - merged['iv_put']

    # Weight by OI
    merged['weight'] = merged['oi_call'] + merged['oi_put']

    iv_spread_by_symbol = (
        merged
        .groupby('symbol')
        .apply(lambda x: np.average(x['iv_spread'], weights=x['weight']))
        .rename('iv_spread')
    )
    return iv_spread_by_symbol


def compute_skew_signal(options_df: pd.DataFrame, S: float, T_target: float = 30/365) -> pd.Series:
    """
    Xing, Zhang & Zhao (2010) IV skew signal.
    IV_skew = IV(25-delta put) - IV(ATM call)
    Predicts weekly cross-sectional returns negatively.
    """
    # Filter to near-target expiry
    mask = abs(options_df['expiry_T'] - T_target) < 7/365
    df = options_df[mask].copy()

    # ATM calls : delta 0.5
    atm_calls = df[(df['option_type'] == 'call') & (abs(df['delta'] - 0.5) < 0.1)]
    otm_puts = df[(df['option_type'] == 'put') & (abs(df['delta'] + 0.25) < 0.1)]

    iv_atm_call = atm_calls.groupby('symbol')['iv'].mean().rename('iv_atm_call')
    iv_25d_put = otm_puts.groupby('symbol')['iv'].mean().rename('iv_25d_put')

    skew = (iv_25d_put - iv_atm_call).rename('iv_skew')
    return skew


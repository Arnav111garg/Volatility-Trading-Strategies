import QuantLib as ql
import numpy as np

# --- Setup dates and calendar ---
today = ql.Date(10, 6, 2025)
ql.Settings.instance().evaluationDate = today
calendar = ql.UnitedStates(ql.UnitedStates.NYSE)
dc = ql.Actual365Fixed()

# --- Market vol surface data ---
spot = 5100.0 # SPX level
r = 0.05; q = 0.02

expiry_dates = [
    ql.Date(19, 9, 2025), # ~3M
    ql.Date(19, 12, 2025), # ~6M
    ql.Date(18, 6, 2026), # ~1Y
]
strikes = [4500, 4750, 5000, 5100, 5250, 5500, 5750]

# Vol matrix (rows = maturities, cols = strikes)
vol_matrix = [
    [0.280, 0.255, 0.230, 0.220, 0.210, 0.200, 0.195], # 3M
    [0.265, 0.245, 0.225, 0.215, 0.205, 0.198, 0.192], # 6M
    [0.250, 0.235, 0.218, 0.210, 0.202, 0.196, 0.190], # 1Y
]

# --- Build QuantLib Black vol surface ---
matrix = ql.Matrix(len(strikes), len(expiry_dates))
for i, row in enumerate(vol_matrix):
    for j, v in enumerate(row):
        matrix[j][i] = v # QL: strikes x maturities

spot_handle = ql.QuoteHandle(ql.SimpleQuote(spot))
r_curve = ql.FlatForward(today, r, dc)
q_curve = ql.FlatForward(today, q, dc)

bvs = ql.BlackVarianceSurface(
    today, calendar, expiry_dates,
    strikes, matrix, dc)
bvs.setInterpolation("bicubic")
bvs.enableExtrapolation()

vol_ts = ql.BlackVolTermStructureHandle(bvs)

# --- Query: implied vol at arbitrary (K, T) ---
def query_iv(K, T_date):
    t = dc.yearFraction(today, T_date)
    return bvs.blackVol(T_date, K)

T_query = ql.Date(19, 9, 2025)
print(f"IV at K=5000, T=Sep2025: {query_iv(5000, T_query):.4f}")
print(f"IV at K=4750, T=Sep2025: {query_iv(4750, T_query):.4f}")

# --- Build Local Vol surface ---
process = ql.BlackScholesMertonProcess(
    spot_handle,
    ql.YieldTermStructureHandle(ql.FlatForward(today, q, dc)),
    ql.YieldTermStructureHandle(ql.FlatForward(today, r, dc)),
    vol_ts)

local_vol_surface = ql.LocalVolSurface(
    vol_ts,
    ql.YieldTermStructureHandle(ql.FlatForward(today, r, dc)),
    ql.YieldTermStructureHandle(ql.FlatForward(today, q, dc)),
    spot_handle)

# Query local vol
T_lv = dc.yearFraction(today, T_query)
lv_atm = local_vol_surface.localVol(T_lv, 5100.0, True)
print(f"Local vol ATM, 3M: {lv_atm:.4f}")


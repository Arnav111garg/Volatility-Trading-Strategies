import numpy as np
from scipy.integrate import quad
from scipy.stats import norm

# Black-Scholes formulas to find implied volatility
def bs_price(S, K, r, q, T, sigma):
    if sigma <= 0:
        return 0.0
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    price = S * np.exp(-q * T) * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    return price

def bs_vega(S, K, r, q, T, sigma):
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    return S * np.exp(-q * T) * norm.pdf(d1) * np.sqrt(T)

def implied_vol_nr(price, S, K, r, q, T, tol=1e-8, max_iter=100):
    # Simple Newton-Raphson solver for implied volatility
    sigma = 0.2  # Initial guess
    for _ in range(max_iter):
        diff = bs_price(S, K, r, q, T, sigma) - price
        if abs(diff) < tol:
            return sigma
        vega = bs_vega(S, K, r, q, T, sigma)
        if vega < 1e-10:
            break
        sigma -= diff / vega
    return sigma

def heston_cf(u, S0, K, r, q, T, v0, kappa, vbar, xi, rho):
    F = S0 * np.exp((r - q) * T)
    a = kappa * vbar

    # Compute d
    d = np.sqrt((rho * xi * 1j * u - kappa)**2 + xi**2 * (1j * u + u**2))

    # g ratio (Albrecher's branch cut fix)
    r_neg = kappa - rho * xi * 1j * u - d
    r_pos = kappa - rho * xi * 1j * u + d
    g = r_neg / r_pos

    # Exponent for D
    exp_dt = np.exp(-d * T)
    D = r_neg / xi**2 * (1 - exp_dt) / (1 - g * exp_dt)

    # Exponent for C
    C = (a / xi**2) * (r_neg * T - 2 * np.log((1 - g * exp_dt) / (1 - g)))

    return np.exp(C + D * v0)

def heston_call_lewis(S0, K, r, q, T, v0, kappa, vbar, xi, rho, n_quad=256):
    """Price European call via Lewis (2001) formula."""
    F = S0 * np.exp((r - q) * T)
    k = np.log(K / F)

    def integrand(u):
        phi = heston_cf(u - 0.5j, S0, K, r, q, T, v0, kappa, vbar, xi, rho)
        return np.real(np.exp(-1j * u * k) * phi / (u**2 + 0.25))

    I, _ = quad(integrand, 0, 200, limit=n_quad, epsabs=1e-10, epsrel=1e-8)
    call = F * np.exp(-r * T) * (1 - np.exp(k) * I / np.pi)
    return call

def heston_iv(S0, K, r, q, T, v0, kappa, vbar, xi, rho):
    """Implied vol of Heston call."""
    price = heston_call_lewis(S0, K, r, q, T, v0, kappa, vbar, xi, rho)
    iv = implied_vol_nr(price, S0, K, r, q, T)
    return iv


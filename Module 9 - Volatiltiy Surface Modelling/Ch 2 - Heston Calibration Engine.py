import numpy as np
from scipy.optimize import differential_evolution, minimize

class HestonCalibrator:
    def __init__(self, S0, r, q, K_grid, T_grid, iv_market, weights=None):
        self.S0 = S0
        self.r = r
        self.q = q
        self.K_grid = K_grid
        self.T_grid = T_grid
        self.iv_mkt = iv_market
        if weights is None:
            self.weights = np.ones_like(iv_market)
        else:
            self.weights = weights

    def model_ivs(self, params):
        v0, kappa, vbar, xi, rho = params
        ivs = np.zeros_like(self.iv_mkt)
        for j, T in enumerate(self.T_grid):
            for i, K in enumerate(self.K_grid):
                try:
                    price = heston_call_lewis(
                        self.S0, K, self.r, self.q, T,
                        v0, kappa, vbar, xi, rho)
                    ivs[i, j] = implied_vol_nr(
                        price, self.S0, K, self.r, self.q, T)
                except Exception:
                    ivs[i, j] = np.nan
        return ivs

    def objective(self, params):
        v0, kappa, vbar, xi, rho = params
        # Bounds check
        if (v0 <= 0 or kappa <= 0 or vbar <= 0
                or xi <= 0 or abs(rho) >= 1):
            return 1e10
        iv_mod = self.model_ivs(params)
        mask = ~np.isnan(iv_mod) & ~np.isnan(self.iv_mkt)
        diff = iv_mod[mask] - self.iv_mkt[mask]
        return np.sum(self.weights[mask] * diff**2)

    def calibrate(self):
        bounds = [
            (1e-4, 0.5),      # v0
            (0.1, 15.0),      # kappa
            (1e-4, 0.5),      # vbar
            (0.01, 3.0),      # xi
            (-0.99, 0.0)      # rho (equity: negative)
        ]

        # Stage 1: Global
        print("Stage 1: Differential Evolution ...")
        res_g = differential_evolution(
            self.objective, bounds, seed=0, maxiter=300,
            tol=1e-8, mutation=(0.5, 1.5), recombination=0.9,
            workers=1)

        # Stage 2: Local
        print("Stage 2: Local optimisation ...")
        res_l = minimize(
            self.objective, res_g.x,
            method='L-BFGS-B', bounds=bounds,
            options={'ftol': 1e-14, 'maxiter': 500})

        v0, kappa, vbar, xi, rho = res_l.x
        feller = 2 * kappa * vbar / xi**2
        return {
            'v0': v0, 'kappa': kappa, 'vbar': vbar,
            'xi': xi, 'rho': rho,
            'feller': feller,
            'rmse': np.sqrt(res_l.fun / self.iv_mkt.size),
            'success': res_l.success
        }


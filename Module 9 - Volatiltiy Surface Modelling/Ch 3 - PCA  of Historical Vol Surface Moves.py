import numpy as np
from sklearn.decomposition import PCA
import matplotlib.pyplot as plt

def pca_vol_surface(iv_history):
  n_days , n_K , n_T = iv_history.shape
  X = iv_history.reshape(n_days, n_K * n_T)
  dX = np.diff (X , axis =0)
  pca = PCA(n_components =min(1 , dX.shape [1]))
  pca.fit(dX)
  loadings = pca.components_.reshape(-1, n_K, n_T)
  variance_explained = pca.explained_variance_ratio_
  return loadings, variance_explained


print (" Typical equity vol surface PCA decomposition :")
pca_components = ["PC1 : Parallel shift ","PC2 : Term structure tilt ", "PC3 : Smile / curvature ", "PC4 : Skew "]
variances = [0.70 , 0.15 , 0.08 , 0.03]
for c , v in zip ( pca_components , variances):
  print (f"{c:35s}:{v:.0%}")

